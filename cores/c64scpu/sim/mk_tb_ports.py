#!/usr/bin/env python3
"""T182: regenerate cores/c64scpu/sim/tb_c64scpu_{ports,inst}.vh from the port list of c64_core_c64scpu (every input a reg at 0, every output a wire).
Run from the repository root after the core's ports change (copy of cores/c128/sim/mk_tb_ports.py)."""
import re
s = open('cores/c64scpu/c64_core_c64scpu.v').read()
i = s.index(') (', s.index('module c64_core_c64scpu'))
j = s.index('\n);', i)
hdr = re.sub(r'//[^\n]*', '', s[i + 3:j])
ports = []
for line in hdr.split('\n'):
    l = line.strip().rstrip(',').strip()
    m = re.match(r'(input|output)\s+(?:wire|reg)\s*(?:signed\s*)?(\[[^\]]+\])?\s*(.*)$', l)
    if not m:
        continue
    d, w, names = m.groups()
    for n in names.split(','):
        n = n.split('=')[0].strip()
        if n:
            ports.append((d, w or '', n))
decl, inst = [], []
for d, w, n in ports:
    decl.append(("    reg  " if d == 'input' else "    wire ") + (w + ' ' if w else '') + n + (" = 0;" if d == 'input' else ";"))
    inst.append("        .%s(%s)" % (n, n))
d = 'cores/c64scpu/sim/'
open(d + 'tb_c64scpu_ports.vh', 'w').write("// generated by mk_tb_ports.py from the port list of c64_core_c64scpu: every input a reg at 0, every output a wire\n" + '\n'.join(decl) + "\n")
open(d + 'tb_c64scpu_inst.vh', 'w').write(',\n'.join(inst) + "\n")
print(len(ports), "ports")
