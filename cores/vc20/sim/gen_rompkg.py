#!/usr/bin/env python3
"""A VHDL package with the three VIC-20 ROM images, for the LOCAL boot bench (tb_vc20_boot.vhd).

    gen_rompkg.py CHAR.bin BASIC.bin KERNAL.bin out.vhd

The images are third-party (Commodore) and are never checked in: point it at copies on your own
machine and keep the output in the (ignored) build directory."""
import sys

char, basic, kernal = (open(p, "rb").read() for p in sys.argv[1:4])
assert len(char) == 4096 and len(basic) == 8192 and len(kernal) == 8192, "sizes 4096/8192/8192"

def arr(name, size, data):
    rows = [", ".join('x"%02X"' % b for b in data[i:i + 8]) for i in range(0, len(data), 8)]
    return ("  type %s_t is array (0 to %d) of std_logic_vector(7 downto 0);\n"
            "  constant %s : %s_t := (\n    %s\n  );\n") % (name.lower(), size - 1, name, name.lower(), ",\n    ".join(rows))

out = ["-- generated by gen_rompkg.py, local use only", "library ieee; use ieee.std_logic_1164.all;",
       "package vc20_rom_pkg is", arr("CHAR", 4096, char), arr("BASIC", 8192, basic), arr("KERNAL", 8192, kernal), "end package;", ""]
open(sys.argv[4], "w").write("\n".join(out))
