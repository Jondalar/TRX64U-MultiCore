#!/usr/bin/env python3
"""A hand-written 6502 test program for the VC-20 bench (no Commodore ROM involved).

It sits in the KERNAL window at $E000: initialise the VIC the way the KERNAL does, then write
the screen codes 0..255 to screen RAM $1E00 and colour 0 (black) to colour RAM $9600, and spin.
Writes vc20_testrom_pkg.vhd (KERNAL bytes at ROM-block offset $2000 + n)."""
import sys

prog = bytes([
    0x78,             # E000 SEI
    0xD8,             # E001 CLD
    0xA2, 0xFF,       # E002 LDX #$FF
    0x9A,             # E004 TXS
    0xA2, 0x0F,       # E005 LDX #$0F
    0xBD, 0x30, 0xE0, # E007 LDA $E030,X
    0x9D, 0x00, 0x90, # E00A STA $9000,X
    0xCA,             # E00D DEX
    0x10, 0xF7,       # E00E BPL E007
    0xA2, 0x00,       # E010 LDX #$00
    0x8A,             # E012 TXA
    0x9D, 0x00, 0x1E, # E013 STA $1E00,X
    0xA9, 0x00,       # E016 LDA #$00
    0x9D, 0x00, 0x96, # E018 STA $9600,X
    0xE8,             # E01B INX
    0xD0, 0xF4,       # E01C BNE E012
    0x4C, 0x1E, 0xE0, # E01E JMP E01E
])
vic = bytes([0x0C, 0x26, 0x96, 0xAE, 0x00, 0xF0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1B])
rom = bytearray(0x2000)
rom[0:len(prog)] = prog
rom[0x30:0x40] = vic
rom[0x1FFC], rom[0x1FFD] = 0x00, 0xE0            # reset vector -> $E000
rom[0x1FFA], rom[0x1FFB] = 0x1E, 0xE0            # NMI, IRQ -> the spin loop
rom[0x1FFE], rom[0x1FFF] = 0x1E, 0xE0
# the memory-map test: write $A5 to the first and last byte of every expansion block, read it back through the
# CPU, store what it read at $0300+n. n = 12 addresses, tables at $E080 (low) and $E0A0 (high)
addrs = [0x0400, 0x0FFF, 0x2000, 0x3FFF, 0x4000, 0x5FFF, 0x6000, 0x7FFF, 0xA000, 0xBFFF, 0x1000, 0x0200]
mem = bytes([
    0x78, 0xD8, 0xA2, 0xFF, 0x9A,          # E000 SEI CLD LDX #$FF TXS
    0xA2, 0x00,                            # E005 LDX #0
    0xBD, 0x80, 0xE0, 0x85, 0xFB,          # E007 LDA $E080,X  STA $FB
    0xBD, 0xA0, 0xE0, 0x85, 0xFC,          # E00C LDA $E0A0,X  STA $FC
    0xA9, 0xA5, 0xA0, 0x00,                # E011 LDA #$A5  LDY #0
    0x91, 0xFB,                            # E015 STA ($FB),Y
    0xB1, 0xFB,                            # E017 LDA ($FB),Y
    0x9D, 0x00, 0x03,                      # E019 STA $0300,X
    0xE8, 0xE0, len(addrs),                # E01C INX  CPX #n
    0xD0, 0xE6,                            # E01F BNE E007 (-26)
    0x4C, 0x21, 0xE0,                      # E021 JMP E021
])
rom2 = bytearray(0x2000)
rom2[0:len(mem)] = mem
for i, a in enumerate(addrs):
    rom2[0x80 + i] = a & 0xFF
    rom2[0xA0 + i] = a >> 8
rom2[0x1FFC], rom2[0x1FFD] = 0x00, 0xE0
rom2[0x1FFA], rom2[0x1FFB] = 0x21, 0xE0
rom2[0x1FFE], rom2[0x1FFF] = 0x21, 0xE0
# the pause test (tb_vc20_pause): sound on, VIA2 T1 free running with its IRQ, T2 counting; the main loop counts in
# $FB/$FC and copies T2's low byte to $FE, the IRQ handler counts in $FD
pz = bytes([
    0x78, 0xD8, 0xA2, 0xFF, 0x9A,          # E000 SEI CLD LDX #$FF TXS
    0xA9, 0x0F, 0x8D, 0x0E, 0x90,          # E005 LDA #$0F STA $900E (volume)
    0xA9, 0xE0, 0x8D, 0x0A, 0x90,          # E00A LDA #$E0 STA $900A (voice on)
    0xA9, 0x40, 0x8D, 0x2B, 0x91,          # E00F LDA #$40 STA $912B (ACR: T1 free run)
    0xA9, 0xC0, 0x8D, 0x2E, 0x91,          # E014 LDA #$C0 STA $912E (IER: T1)
    0xA9, 0xFF, 0x8D, 0x24, 0x91,          # E019 LDA #$FF STA $9124 (T1 latch low)
    0xA9, 0x03, 0x8D, 0x25, 0x91,          # E01E LDA #$03 STA $9125 (T1 high: start)
    0x8D, 0x29, 0x91,                      # E023 STA $9129 (T2 high: start)
    0x58,                                  # E026 CLI
    0xE6, 0xFB,                            # E027 INC $FB
    0xD0, 0x02,                            # E029 BNE E02D
    0xE6, 0xFC,                            # E02B INC $FC
    0xAD, 0x28, 0x91,                      # E02D LDA $9128 (T2 low)
    0x85, 0xFE,                            # E030 STA $FE
    0x4C, 0x27, 0xE0,                      # E032 JMP E027
])
irq = bytes([0xAD, 0x24, 0x91, 0xE6, 0xFD, 0x40])   # E040 LDA $9124 (clears the flag) INC $FD RTI
rom3 = bytearray(0x2000)
rom3[0:len(pz)] = pz
rom3[0x40:0x40 + len(irq)] = irq
rom3[0x1FFC], rom3[0x1FFD] = 0x00, 0xE0
rom3[0x1FFA], rom3[0x1FFB] = 0x27, 0xE0
rom3[0x1FFE], rom3[0x1FFF] = 0x40, 0xE0
out = ["-- generated by gen_testrom.py", "library ieee; use ieee.std_logic_1164.all;",
       "package vc20_testrom_pkg is",
       "  type rom8k_t is array (0 to 8191) of std_logic_vector(7 downto 0);",
       "  constant KERNAL : rom8k_t := ("]
rows = []
for i in range(0, 0x2000, 8):
    rows.append("    " + ", ".join('x"%02X"' % b for b in rom[i:i + 8]))
out.append(",\n".join(rows))
rows2 = []
for i in range(0, 0x2000, 8):
    rows2.append("    " + ", ".join('x"%02X"' % b for b in rom2[i:i + 8]))
rows3 = []
for i in range(0, 0x2000, 8):
    rows3.append("    " + ", ".join('x"%02X"' % b for b in rom3[i:i + 8]))
out += ["  );", "  constant KERNAL_MEM : rom8k_t := (", ",\n".join(rows2), "  );",
        "  constant KERNAL_PAUSE : rom8k_t := (", ",\n".join(rows3), "  );", "end package;", ""]
open(sys.argv[1] if len(sys.argv) > 1 else "vc20_testrom_pkg.vhd", "w").write("\n".join(out))
