#!/usr/bin/env python3
"""T90: the two keyboard matrices as grids of key names, and the translation between them (D7). The grids are
written from the two machines' keyboards, not from the C16Nano PS/2 decoder:

  C64   keys[col * 8 + row], 1 = down (CIA 1: port A = column, port B = row)
  C264  col c, row r: the TED reads k[c] low when a key of column c is down in a row whose 6529 bit is low

c264_keys.v is generated from this file (python3 keymap.py > ../../../cores/c264/rtl/trx/c264_keys.v); tb_c264_keys.v
reads the vectors from `python3 keymap.py vectors`, which are computed by name, not from the generated assigns.
"""
import sys

C64 = [  # per column, rows 0..7
    ["DEL", "RETURN", "CRSR_R", "F7", "F1", "F3", "F5", "CRSR_D"],
    ["3", "W", "A", "4", "Z", "S", "E", "LSHIFT"],
    ["5", "R", "D", "6", "C", "F", "T", "X"],
    ["7", "Y", "G", "8", "B", "H", "U", "V"],
    ["9", "I", "J", "0", "M", "K", "O", "N"],
    ["+", "P", "L", "-", ".", ":", "@", ","],
    ["POUND", "*", ";", "HOME", "RSHIFT", "=", "UARROW", "/"],
    ["1", "LARROW", "CTRL", "2", "SPACE", "C=", "Q", "STOP"],
]
C264 = [
    ["DEL", "3", "5", "7", "9", "DOWN", "LEFT", "1"],
    ["RETURN", "W", "R", "Y", "I", "P", "*", "HOME"],
    ["POUND", "A", "D", "G", "J", "L", ";", "CTRL"],
    ["HELP", "4", "6", "8", "0", "UP", "RIGHT", "2"],
    ["F1", "Z", "C", "B", "M", ".", "ESC", "SPACE"],
    ["F2", "S", "F", "H", "K", ":", "=", "C="],
    ["F3", "E", "T", "U", "O", "-", "+", "Q"],
    ["@", "SHIFT", "X", "V", "N", ",", "/", "STOP"],
]
# C64 key name -> C264 key name (None: the C264 has no such key). The cursor keys and SHIFT are done separately.
RENAME = {"F7": "HELP", "F1": "F1", "F3": "F2", "F5": "F3", "LARROW": "ESC", "UARROW": None}
SPECIAL = ("CRSR_R", "CRSR_D", "LSHIFT", "RSHIFT")

def pos64(name):
    for c, col in enumerate(C64):
        if name in col:
            return c * 8 + col.index(name)
    raise KeyError(name)

def pos264(name):
    for c, col in enumerate(C264):
        if name in col:
            return c * 8 + col.index(name)
    raise KeyError(name)

def translate(down):
    """down: set of C64 key names -> set of C264 key names"""
    out = set()
    shift = "LSHIFT" in down or "RSHIFT" in down
    cur = "CRSR_R" in down or "CRSR_D" in down
    for k in down:
        if k in SPECIAL:
            continue
        n = RENAME.get(k, k)
        if n is not None:
            out.add(n)
    if "CRSR_D" in down:
        out.add("UP" if shift else "DOWN")
    if "CRSR_R" in down:
        out.add("LEFT" if shift else "RIGHT")
    if shift and not cur:
        out.add("SHIFT")
    return out

def to_vec264(names):
    v = 0
    for n in names:
        v |= 1 << pos264(n)
    return v

def to_vec64(names):
    v = 0
    for n in names:
        v |= 1 << pos64(n)
    return v

def verilog():
    L = []
    w = L.append
    w("// T90: the host's C64 key matrix (keys[col*8+row], 1 = down) into the C264 matrix (k264[col*8+row], 1 = down). Generated by")
    w("// cores/c264/sim/keymap.py from the two keyboards' key names; do not edit by hand. Written for this project.")
    w("// Positional: the C64 keys with the same legend map to the same key; F1/F3/F5/F7 -> F1/F2/F3/HELP; back-arrow -> ESC;")
    w("// CRSR down/right with SHIFT -> UP/LEFT (SHIFT is removed from the C264 matrix then); up-arrow and RESTORE have no C264 key.")
    w("`timescale 1ns / 1ps")
    w("module c264_keys (")
    w("    input  wire [63:0] keys,")
    w("    output wire [63:0] k264")
    w(");")
    w("    wire shift = keys[%d] | keys[%d];" % (pos64("LSHIFT"), pos64("RSHIFT")))
    w("    wire cur_d = keys[%d];" % pos64("CRSR_D"))
    w("    wire cur_r = keys[%d];" % pos64("CRSR_R"))
    for name in sorted({n for col in C264 for n in col}, key=pos264):
        p = pos264(name)
        srcs = []
        if name == "UP":
            e = "cur_d & shift"
        elif name == "DOWN":
            e = "cur_d & ~shift"
        elif name == "LEFT":
            e = "cur_r & shift"
        elif name == "RIGHT":
            e = "cur_r & ~shift"
        elif name == "SHIFT":
            e = "shift & ~cur_d & ~cur_r"
        else:
            src = [k for k in {n for col in C64 for n in col} if k not in SPECIAL and RENAME.get(k, k) == name]
            assert len(src) == 1, (name, src)
            e = "keys[%d]" % pos64(src[0])
        w("    assign k264[%d] = %s;   // %s" % (p, e, name))
    w("endmodule")
    return "\n".join(L) + "\n"

if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "vectors":
        names64 = sorted({n for col in C64 for n in col})
        cases = [{n} for n in names64]
        cases += [{"LSHIFT", n} for n in names64 if n != "LSHIFT"] + [{"RSHIFT", n} for n in names64 if n != "RSHIFT"]
        cases += [{"CRSR_D", "CRSR_R"}, {"CRSR_D", "CRSR_R", "LSHIFT"}, set()]
        for c in cases:
            print("%016x %016x" % (to_vec64(c), to_vec264(translate(c))))
    else:
        sys.stdout.write(verilog())
