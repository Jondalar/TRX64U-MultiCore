def bterm(t):
    if t == 'SHIFT':
        return '(keys[15] | keys[52])'
    if t.startswith('sym:'):
        return '(keys[%d] & ~keys[61])' % DIG[t[4:]]
    if t.startswith('pad:'):
        return '(keys[%d] & keys[61])' % DIG[t[4:]]
    if t == 'padpt':
        return '(keys[44] & keys[61])'
    if t in ('.', ','):
        return '(keys[%d] & ~keys[61])' % C64[t]
    return 'keys[%d]' % C64[t]


def term(t):
    if t == 'SHIFT':
        return '(keys[15] | keys[52])'
    if t == 'CBM':
        return '(keys[61] & ~dig)'
    if t.startswith('sym:'):
        return '(keys[%d] & ~keys[61])' % DIG[t[4:]]
    if t.startswith('pad:'):
        return '(keys[%d] & keys[61])' % DIG[t[4:]]
    return 'keys[%d]' % C64[t]


