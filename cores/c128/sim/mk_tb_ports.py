#!/usr/bin/env python3
"""T113: regenerate cores/c128/sim/tb_c128_{ports,inst,inst_cache}.vh from the port list of c64_core_c128 (every input a reg at 0, every
output a wire). Run from the repository root after the core's ports change."""
import re
s = open('cores/c128/c64_core_c128.v').read()
i = s.index(') (', s.index('module c64_core_c128'))
j = s.index('\n);', i)
hdr = re.sub(r'//[^\n]*', '', s[i + 3:j])
ports = []
mode = None
for line in hdr.split('\n'):
    l = line.strip()
    if l.startswith('`ifdef'):
        mode = l.split()[1]; continue
    if l.startswith('`else'):
        mode = 'ELSE'; continue
    if l.startswith('`endif'):
        mode = None; continue
    l = l.rstrip(',').strip()
    m = re.match(r'(input|output)\s+(?:wire|reg)\s*(?:signed\s*)?(\[[^\]]+\])?\s*(.*)$', l)
    if not m:
        continue
    d, w, names = m.groups()
    for n in names.split(','):
        n = n.split('=')[0].strip()
        if n:
            ports.append((d, w or '', n, mode))
decl, inst, cinst, rinst = [], [], [], []
for d, w, n, mode in ports:
    decl.append(("    reg  " if d == 'input' else "    wire ") + (w + ' ' if w else '') + n + (" = 0;" if d == 'input' else ";"))
    (cinst if mode == 'ROM_CACHE' else rinst if mode == 'RAM_DDR2' else inst).append("        .%s(%s)" % (n, n))
d = 'cores/c128/sim/'
open(d + 'tb_c128_ports.vh', 'w').write("// generated by mk_tb_ports.py from the port list of c64_core_c128: every input a reg at 0, every output a wire\n" + '\n'.join(decl) + "\n")
open(d + 'tb_c128_inst.vh', 'w').write(',\n'.join(inst) + "\n")
open(d + 'tb_c128_inst_cache.vh', 'w').write(',\n'.join(cinst) + "\n")
open(d + 'tb_c128_inst_ramd.vh', 'w').write(',\n'.join(rinst) + "\n")
print(len(ports), "ports")
