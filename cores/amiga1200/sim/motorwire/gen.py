#!/usr/bin/env python3
"""T159 S4c: builds the wiring bench from the shipped sources: layer2_amiga.v as shipped (the A500 and the A1200 share the wiring since T159 D-all),
top.v's case-LED and bling_io lines (extracted, not copied), a stub amiga_core whose drv_led the bench drives. usage: gen.py <root> <outdir>"""
import re, sys
root, out = sys.argv[1], sys.argv[2]
l2 = open(f'{root}/cores/amiga/layer2_amiga.v').read()
for need in ('.drv_led(a_drv_led), .drv_hd(a_drv_hd));', "assign drive_leds_n = {1'b1, ~a_drv_hd, ~a_drv_led};", 'a_drv_led, a_drv_hd;'):
    assert l2.count(need) == 1, need
open(f'{out}/layer2_patched.v', 'w').write(l2)
inst = re.search(r"amiga_core #\(.*?\) amiga \((.*?)\);", l2, re.S).group(1)
ports = sorted(set(re.findall(r"\.(\w+)\(", inst)))
stub = "module amiga_core #(parameter CHS_INIT=0, MEM_INIT=0, HDF_SECT=0) (\n" + ",\n".join(
    (f"  output reg {p} = 1'b0" if p in ('drv_led', 'drv_hd') else f"  input {p}") for p in ports) + ");\nendmodule\n"
open(f'{out}/amiga_core_stub.v', 'w').write(stub)
top = open(f'{root}/cores/amiga1200/mono/host/top.v').read()
m = re.search(r"(    always @\(posedge cpu_clk\) begin\n        cled_s1 <=.*?\.led1n\(led1n\), \.led2n\(led2n\)\);)", top, re.S)
cled = m.group(1)
b = re.search(r"(    bling_io bio \(.*?\.bling_led\(BLING_LED\)\);)", top, re.S).group(1)
decl = re.search(r"(    \(\* ASYNC_REG = \"TRUE\" \*\) reg \[2:0\] cled_s1, cled_s2;)", top).group(1)
w = f"""// generated by gen.py: top.v's case-LED + bling lines around the patched layer2
module wire_top (input cpu_clk, input [7:0] caseled_sel, input caseled_set, output BLING_LED, output led1n_o);
    wire [2:0] drive_leds_n;
    wire gt_ready, video_locked_s, busy_usb, busy_any, cpu_rst;
    assign gt_ready = 1'b1; assign video_locked_s = 1'b1; assign busy_usb = 1'b0; assign busy_any = 1'b0; assign cpu_rst = 1'b0;
    wire [2:0] c64_leds; assign c64_leds = 3'b000;
    wire bl_we, bl_irq, bl_rx_tgl, bl_locked, bl_lock_off;
    assign bl_we = 1'b0; assign bl_rx_tgl = 1'b0; assign bl_locked = 1'b0;
    wire [11:0] bl_addr; wire [7:0] bl_wdata, bl_rdata, bl_last;
    assign bl_addr = 12'h000; assign bl_wdata = 8'h00; assign bl_last = 8'h00;
    layer2 l2 (.cpu_clk(cpu_clk), .drive_leds_n(drive_leds_n));
{decl}
{b}
{cled}
    assign led1n_o = led1n;
endmodule
"""
w = w.replace("layer2 l2", "layer2_amiga l2")
open(f'{out}/wire_top.v', 'w').write(w)
