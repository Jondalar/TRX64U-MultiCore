// T189: tone preset of every core (host/top.v): Flat / Bass boost / Treble boost, a shelf filter on the two 24-bit audio samples BEFORE the master
// volume (trx_gain.v), so the gain's sat stays the only clip point. Output 25 bit (exactly the +6 dB of a shelf); Flat sign-extends the input
// (combinational, bit-exact, no latency).
// One biquad per channel, direct form I, coefficients 18 bit (Q2.16 for the bass set, Q3.15 for the treble set), one multiply-accumulate per clock on one DSP48 per channel (5 per sample,
// 256 clocks per frame). Presets are exclusive: sel 1 = low shelf 200 Hz +6 dB, sel 2 = high shelf 4 kHz +6 dB, anything else Flat. A preset
// change clears the filter state.
// Timing in the frame: frame_en (i2s_out, half a frame before the I2S frame start) -> WAIT clocks for the core to present its pair -> capture ->
// filter -> the output register changes about 40 clocks after frame_en and then holds for the rest of the frame: the HDMI hold (taken at the next
// frame_en) and the I2S frame start (127 clocks after frame_en) take the same sample pair (T189 S5). A filtered sample is one frame late.
// The select byte comes from the register block (cpu_clk, quasi static): two flip-flops into clk, accepted when two reads agree (as trx_gain).
// Written for this project.
`timescale 1ns / 1ps
module trx_tone (
    input  wire               clk,                     // mclk, 12.288 MHz
    input  wire               frame_en,                // one clk per 48 kHz frame
    input  wire [7:0]         sel,                     // another clock, quasi static: 0 Flat, 1 Bass boost, 2 Treble boost
    input  wire signed [23:0] in_l,
    input  wire signed [23:0] in_r,
    output wire signed [24:0] out_l,
    output wire signed [24:0] out_r
);
    (* ASYNC_REG = "TRUE" *) reg [7:0] s1 = 8'h00, s2 = 8'h00;
    reg [1:0] mode = 2'd0;                              // 0 Flat, 1 Bass, 2 Treble
    reg       chg  = 1'b0;                              // mode changed: clear the state
    always @(posedge clk) begin
        s1 <= sel; s2 <= s1;
        chg <= 1'b0;
        if (s1 == s2) begin
            if (s2 == 8'd1 && mode != 2'd1) begin mode <= 2'd1; chg <= 1'b1; end
            else if (s2 == 8'd2 && mode != 2'd2) begin mode <= 2'd2; chg <= 1'b1; end
            else if (s2 != 8'd1 && s2 != 8'd2 && mode != 2'd0) begin mode <= 2'd0; chg <= 1'b1; end
        end
    end

    reg [5:0] wc = 6'd63;                               // 0..: counts from frame_en, 63 = idle
    reg       go = 1'b0;
    always @(posedge clk) begin
        go <= 1'b0;
        if (frame_en) wc <= 6'd0;
        else if (wc != 6'd63) wc <= wc + 6'd1;
        if (wc == 6'd16) go <= 1'b1;
    end

// coefficients: generated by host/sim/tone/gen_coeffs.py, do not edit between the markers
// COEF BEGIN
    localparam signed [17:0] BASS_B0 = 65958;
    localparam signed [17:0] BASS_B1 = -129015;
    localparam signed [17:0] BASS_B2 = 63119;
    localparam signed [17:0] BASS_A1N = 129031;
    localparam signed [17:0] BASS_A2N = -63526;
    localparam signed [17:0] TREB_B0 = 57708;
    localparam signed [17:0] TREB_B1 = -79982;
    localparam signed [17:0] TREB_B2 = 30841;
    localparam signed [17:0] TREB_A1N = 37950;
    localparam signed [17:0] TREB_A2N = -13748;
// COEF END
    // the sequencer and the coefficient mux are shared by the two channels (they run in step): 5 multiply-accumulate steps k = 0..4 after go
    reg [2:0] k = 3'd0;
    reg       run = 1'b0, v1 = 1'b0, v2 = 1'b0, l1 = 1'b0, l2 = 1'b0, l3 = 1'b0;
    always @(posedge clk) begin
        v1 <= run; v2 <= v1;                            // operand registers valid, product valid
        l1 <= run && (k == 3'd4); l2 <= l1; l3 <= l2;   // the last operand pair, its product, the final sum
        if (chg) begin run <= 1'b0; v1 <= 1'b0; v2 <= 1'b0; l1 <= 1'b0; l2 <= 1'b0; l3 <= 1'b0; end
        else begin
            if (go) begin k <= 3'd0; run <= 1'b1; end
            if (run) begin k <= k + 3'd1; if (k == 3'd4) run <= 1'b0; end
        end
    end
`ifdef TRX_TONE_MUT_SWAP
    wire [1:0] cm = (mode == 2'd1) ? 2'd2 : 2'd1;       // negative control: the two coefficient sets swapped
`else
    wire [1:0] cm = mode;
`endif
    wire signed [17:0] cf = (k == 3'd0) ? ((cm == 2'd1) ? BASS_B0  : TREB_B0)  :
                            (k == 3'd1) ? ((cm == 2'd1) ? BASS_B1  : TREB_B1)  :
                            (k == 3'd2) ? ((cm == 2'd1) ? BASS_B2  : TREB_B2)  :
                            (k == 3'd3) ? ((cm == 2'd1) ? BASS_A1N : TREB_A1N) : ((cm == 2'd1) ? BASS_A2N : TREB_A2N);
    wire signed [24:0] yl, yr;
    trx_tone_ch chl (.clk(clk), .go(go), .chg(chg), .q16(mode == 2'd1), .k(k), .run(run), .v2(v2), .l3(l3), .cf(cf), .x(in_l), .y(yl));
    trx_tone_ch chr (.clk(clk), .go(go), .chg(chg), .q16(mode == 2'd1), .k(k), .run(run), .v2(v2), .l3(l3), .cf(cf), .x(in_r), .y(yr));
`ifdef TRX_TONE_MUT_STUCK
    wire flat = 1'b0;                                   // negative control: stuck in the filter
`else
    wire flat = (mode == 2'd0);
`endif
    assign out_l = flat ? {in_l[23], in_l} : yl;
    assign out_r = flat ? {in_r[23], in_r} : yr;
endmodule

module trx_tone_ch (
    input  wire               clk,
    input  wire               go,                       // take x and compute one output
    input  wire               chg,                      // clear the state
    input  wire               q16,                      // the bass set (Q2.16), else the treble set (Q3.15)
    input  wire [2:0]         k,                        // the step (shared sequencer)
    input  wire               run, v2, l3,
    input  wire signed [17:0] cf,                       // its coefficient
    input  wire signed [23:0] x,
    output reg  signed [24:0] y = 25'sd0
);
    reg signed [23:0] x0 = 24'sd0, x1 = 24'sd0, x2 = 24'sd0;
    reg signed [24:0] y1 = 25'sd0, y2 = 25'sd0;
    reg signed [24:0] a_r = 25'sd0;
    reg signed [17:0] b_r = 18'sd0;
    reg signed [42:0] p_r = 43'sd0;
    reg signed [47:0] acc = 48'sd0;
    reg signed [17:0] rem_q = 18'sd0;                   // the rounding remainder of the last sample

    wire signed [24:0] op = (k == 3'd0) ? {x0[23], x0} : (k == 3'd1) ? {x1[23], x1} : (k == 3'd2) ? {x2[23], x2} : (k == 3'd3) ? y1 : y2;

    // The sum starts at the last sample's rounding remainder plus half an output step, so the floor of the final sum is the output rounded to nearest (Q16 for
    // the bass set, Q15 for the treble set), saturated at 25 bit; the low bits left over minus the half step are the next remainder (first-order error feedback:
    // no dead band around zero, so no DC offset stays behind and DC gains are not lost to rounding).
    wire signed [17:0] half = q16 ? 18'sd32768 : 18'sd16384;
    wire signed [32:0] ys   = q16 ? {acc[47], acc[47:16]} : acc[47:15];
    wire               ov   = (ys > 33'sd16777215) || (ys < -33'sd16777216);
    wire signed [24:0] ysat = (ys > 33'sd16777215) ? 25'sh0FFFFFF : (ys < -33'sd16777216) ? 25'sh1000000 : ys[24:0];
    wire signed [17:0] rem  = ov ? 18'sd0 : ({2'b00, q16 ? acc[15:0] : {1'b0, acc[14:0]}} - half);

    always @(posedge clk) begin
        p_r <= a_r * b_r;
        if (chg) begin
            x0 <= 24'sd0; x1 <= 24'sd0; x2 <= 24'sd0; y1 <= 25'sd0; y2 <= 25'sd0; y <= 25'sd0; rem_q <= 18'sd0;
        end else begin
            if (go) begin x0 <= x; acc <= rem_q + half; end
            if (run) begin a_r <= op; b_r <= cf; end
            if (v2) acc <= acc + p_r;
            if (l3) begin
                y <= ysat; rem_q <= rem; y1 <= ysat; y2 <= y1; x1 <= x0; x2 <= x1;
            end
        end
    end
endmodule
