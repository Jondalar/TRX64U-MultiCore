#!/usr/bin/env python3
"""T168: the declarations of a bench for the partition's real edge: every port of a layer-2 module (inputs as regs at 0, outputs as wires), read from the module's own
header, written as an include file for the bench, which instantiates the module with `.*`.   mk_l2ports.py <layer2_*.v> <out.vh>"""
import re, sys

src = open(sys.argv[1]).read()
m = re.search(r"module\s+layer2_\w+\b.*?\)\s*;", src, re.S)
ports = re.findall(r"(input|output)\s+wire\s+(signed\s+)?(\[[^\]]+\]\s+)?(\w+)", m.group(0))
lines = []
for d, sg, w, n in ports:
    w = (w or "").strip()
    sg = sg or ""
    lines.append(("    reg %s%s %s = 0;" if d == "input" else "    wire %s%s %s;") % (sg, w, n))
open(sys.argv[2], "w").write("// generated by mk_l2ports.py from %s: %d ports\n%s\n" % (sys.argv[1], len(ports), "\n".join(lines)))
