#!/usr/bin/env python3
"""The test cache of the application tests and the render benches (T100 D13, D14). One unit is a test program (built, run) or a negative
control (the same test against a broken copy of one source) or a render bench. Its outcome is a function of what it reads, which has two
parts, kept apart:

  key       what the BUILD reads and the unit itself: the compiler's -MM dependency list of the unmutated tree (test, sources, every
            header - the mutated file is among them), the unit's id (name, file, sed, sources, flags, compiler line), the files named in
            its run arguments, and the fixtures a suite generated into its scratch directory under the same names.
  manifest  what the RUN reads, recorded by tests/readlog.c while the unit passed: every file, directory listing or missing path under
            the tree it opened or looked at (goldens, python tools and their imports, product sources a test scans). The entry the cache
            keeps for a key is this list with the content hash of each item; a hit needs every item to match NOW.

A control is stored only when it failed as it must, a test only when it passed, so an entry can only stand for that outcome. Nothing is
declared by hand: a file the run opens is found by the recorder, a header by the preprocessor. What cannot be seen (the recorder is a
Linux LD_PRELOAD) falls back to the old coarse key: all data files of the suite directory, all tools/*.py and the product trees a few tests
scan are part of the key (mode "coarse"). A fixture the run reads from the scratch directory (generated by the suite before the unit) is part of
the manifest by its content like a file of the tree, so it needs no declaration; one that is not reproducible byte for byte only costs
a re-run ("reads changed (<T>/...)" in the log), never a stale PASS.

  ctlcache.py key    --root R --tmp T --id ID [--runargs S] [--extra F...] [--mode dyn|coarse] [--suite-dir D] < -MM output
  ctlcache.py record --root R --tmp T --log L [--runargs S] [--extra F...]       -> manifest lines on stdout 
  ctlcache.py verify --root R --tmp T --entry E  -> exit 0 when every item of the manifest matches
"""
import argparse, hashlib, os, sys

BIG = 64 << 20   # files above this are named by size in a manifest
# coarse mode only: tests that read product files at run time besides what they compile: test basename -> paths (relative to the root)
RUNTIME_READS = {
    "test_noflash.cc": ["coreapp/src", "coreapp/cores"],
    "test_amiga500.cc": ["cores/amiga/rtl/trx/amiga_regs.v"],
}


def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for blk in iter(lambda: f.read(1 << 20), b""):
            h.update(blk)
    return h.hexdigest()


def expand(p):
    """a file -> [file]; a directory -> every file below it; a missing path -> [p] (hashed as missing)"""
    if os.path.isdir(p):
        out = []
        for d, ds, fs in os.walk(p):
            ds[:] = sorted(x for x in ds if x not in ("__pycache__", ".git"))
            out += [os.path.join(d, f) for f in sorted(fs)]
        return out
    return [p]


class Ctx:
    def __init__(self, root, tmp):
        self.root = os.path.realpath(root)
        self.tmp = os.path.realpath(tmp) if tmp else ""
        self.raw_root = root

    def under(self, p, base):
        return bool(base) and (p == base or p.startswith(base + "/"))

    def name(self, p):
        """a stable name: relative to the tree, <T>/... under the scratch directory (its own name is random), else as is"""
        if self.under(p, self.root):
            return p[len(self.root) + 1:] if p != self.root else "."
        if self.under(p, self.tmp):
            return "<T>/" + (p[len(self.tmp) + 1:] if p != self.tmp else "")
        return p

    def norm(self, s):
        for a, b in ((self.root, "<root>"), (self.raw_root, "<root>"), (self.tmp, "<T>")):
            if a:
                s = s.replace(a, b)
        return s


def declared_files(ctx, runargs, extra):
    """the files the caller named: run arguments and extras that exist, plus the corpus directory, expanded"""
    out = set()
    words = (runargs or "").split() + list(extra or [])
    corpus = os.environ.get("ZX_CORPUS")
    if corpus:
        words.append(corpus)
    for w in words:
        if os.path.exists(w):
            out.update(expand(os.path.realpath(w)))
    return out


def cmd_key(a):
    if not a.key_version:
        sys.exit("ctlcache.py key: --key-version (CC_KEY_VERSION of tests/ctlcache.sh) is missing")
    ctx = Ctx(a.root, a.tmp)
    text = sys.stdin.read().replace("\\\n", " ")
    deps = set()
    for tok in text.split():
        if tok.endswith(":"):
            continue
        deps.add(os.path.realpath(tok))
    files = set()
    for d in deps:
        files.update(expand(d))
        if a.mode == "coarse":
            for rel in RUNTIME_READS.get(os.path.basename(d), []):
                files.update(expand(os.path.join(ctx.root, rel)))
    files.update(declared_files(ctx, a.runargs, a.extra))
    if a.mode == "coarse":
        if a.suite_dir:
            for p in expand(os.path.join(ctx.root, a.suite_dir)):
                if not p.endswith((".cc", ".h")):
                    files.add(p)
        tools = os.path.join(ctx.root, "tools")
        if os.path.isdir(tools):
            files.update(os.path.join(tools, f) for f in sorted(os.listdir(tools)) if f.endswith(".py"))
    h = hashlib.sha256()
    h.update(("v" + a.key_version + "\0" + a.mode + "\0" + ctx.norm(a.id) + "\0" + ctx.norm(a.runargs or "") + "\0").encode())
    for f in sorted(files, key=ctx.name):
        h.update(ctx.name(f).encode() + b"\0" + (sha(f).encode() if os.path.isfile(f) else b"missing") + b"\0")
    print(h.hexdigest()[:16])


def listing_hash(d):
    names = sorted(n for n in os.listdir(d) if n not in ("__pycache__", ".git"))
    return hashlib.sha256("\n".join(names).encode()).hexdigest()


def item_state(ctx, kind, rel):
    """the manifest line for one item as it is now: F <sha> <rel>, L <sha> <rel>, E <rel>, M <rel>"""
    p = os.path.join(ctx.tmp, rel[4:]) if rel.startswith("<T>/") else os.path.join(ctx.root, rel)
    if kind == "L":
        return "L %s %s" % (listing_hash(p), rel) if os.path.isdir(p) else "M %s" % rel
    if os.path.isfile(p):
        size = os.path.getsize(p)
        if size > BIG:   # a sparse image of gigabytes (the render bench's MegaAGS.hdf): the size stands for the content, hashing it would take longer than the unit
            return "F big:%d %s" % (size, rel)
        return "F %s %s" % (sha(p), rel)
    if os.path.isdir(p):
        return "E %s" % rel
    return "M %s" % rel


def cmd_record(a):
    ctx = Ctx(a.root, a.tmp)
    reads, writes, lists = {}, set(), set()
    try:
        lines = open(a.log, errors="replace").read().splitlines()
    except FileNotFoundError:
        lines = []
    for ln in lines:
        if len(ln) < 3 or ln[1] != " ":
            continue
        kind, path = ln[0], os.path.realpath(os.path.normpath(ln[2:]))
        if kind == "W":
            writes.add(path)
        elif kind == "L":
            lists.add(path)
        else:
            reads[path] = 1
    skip = lambda p: "/__pycache__/" in p + "/" or p.endswith(".pyc") or "/.git/" in p + "/"
    try:   # the moment the unit started: a file made or changed since then is the unit's own product (the shell's redirections are not seen by the recorder)
        start_ns = os.stat(a.log + ".start").st_mtime_ns
    except OSError:
        start_ns = None
    manifest = set()
    for p in list(reads) + list(lists):
        if skip(p) or p in writes:   # a path the unit wrote is its own product (or an output it looked for first), not an input
            continue
        try:
            if start_ns is not None and os.stat(p).st_mtime_ns >= start_ns:
                continue
        except OSError:
            pass
        if ctx.under(p, ctx.root):
            manifest.add(item_state(ctx, "L" if p in lists else "R", ctx.name(p)))
        elif ctx.under(p, ctx.tmp) and (p in lists or os.path.isfile(p)):   # the scratch directory: only what was read from it (its probes are the unit's own)
            manifest.add(item_state(ctx, "L" if p in lists else "R", ctx.name(p)))
    print("\n".join(sorted(manifest)))


def cmd_verify(a):
    ctx = Ctx(a.root, a.tmp)
    try:
        lines = open(a.entry).read().splitlines()[1:]
    except OSError:
        sys.exit(1)
    for ln in lines:
        if not ln:
            continue
        parts = ln.split(" ", 2)
        kind = parts[0]
        rel = parts[2] if kind in ("F", "L") else parts[1]
        now = item_state(ctx, "L" if kind == "L" else "R", rel)
        if now != ln:
            if os.environ.get("CC_WHY"):
                sys.stderr.write("changed: %s\n" % rel)
            sys.exit(1)
    sys.exit(0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["key", "record", "verify"])
    ap.add_argument("--root", required=True)
    ap.add_argument("--tmp", default="")
    ap.add_argument("--id", default="")
    ap.add_argument("--log", default="")
    ap.add_argument("--mode", default="dyn", choices=["dyn", "coarse"])
    ap.add_argument("--suite-dir", default="")
    ap.add_argument("--runargs", default="")
    ap.add_argument("--extra", nargs="*", default=[])
    ap.add_argument("--entry", default="")
    ap.add_argument("--key-version", default="")   # CC_KEY_VERSION of tests/ctlcache.sh: the harness is in a key by this number, not by its bytes (T174 D3)
    a = ap.parse_args()
    {"key": cmd_key, "record": cmd_record, "verify": cmd_verify}[a.cmd](a)


main()
