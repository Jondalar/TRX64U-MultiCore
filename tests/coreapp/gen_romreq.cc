static void emit(const char *core, const char *folder, const char *role, const char *names, const uint32_t *sizes, int flags, int set)
{
    printf("    { \"%s\", \"%s\", \"%s\", \"%s\", { ", core, folder, role, names);
    for (int i = 0; i < 3; i++) {
        printf("%u%s", (unsigned)(sizes ? sizes[i] : 0), i < 2 ? ", " : "");
    }
    printf(" }, %d, %d },\n", flags, set);
}

// TRX64U is TRX64-Ultimate's core since T239.3 P1-8: no descriptor of ours names its ROMs, but the host's maintenance page still checks them for trx64u.cor. Its rows
// are fixed here, after the Neo Geo's, where the table has had them.
static void emit_trx64u()
{
    static const uint32_t k8[3] = { 8192, 0, 0 }, kchar[3] = { 4096, 0, 0 }, kdrv[3] = { 16384, 32768, 0 };
    emit("TRX64U", "c64", "BASIC", "basic-901226-01.bin|basic.bin|basic.901226-01|basic.901226-01.bin|basic.rom", k8, 1, 0);
    emit("TRX64U", "c64", "KERNAL", "kernal-901227-03.bin|kernal.bin|kernal.901227-03|kernal.901227-03.bin|kernal.rom", k8, 1, 0);
    emit("TRX64U", "c64", "CHAR", "chargen-901225-01.bin|chars.bin|characters.901225-01|characters.901225-01.bin|chargen.bin|chars.rom", kchar, 1, 0);
    emit("TRX64U", "c64", "1541 drive", "1541.rom|1541.bin|1541-ii.bin|1541-ii.rom|1541ii.rom|1541c.rom|dos1541.rom|dos1541-325302-01+901229-05.bin", kdrv, 2, 0);
}

int main()
{
    printf("// Generated by tests/coreapp/gen_romreq.cc from coreapp/src/table.cc (and the fixed rows of TRX64U) - do not edit; tests/coreapp/run.sh compares it.\n");
    printf("// core = the manifest name, role, names = file names separated by '|' (a ROM set: the extension), sizes, flags (1 required,\n");
    printf("// 2 shared device ROM, 4 one file of the extension out of a set), set = bit mask of the variants (desc.h)\n");
    for (const CoreDesc *const *p = core_table; *p; p++) {
        const CoreDesc *d = *p;
        for (int i = 0; i < d->nroms; i++) {
            const RomSpec &r = d->roms[i];
            char names[200] = "";
            for (int k = 0; k < ROM_NAMES_MAX && r.names[k]; k++) {
                if (k) {
                    strcat(names, "|");
                }
                strcat(names, r.names[k]);
            }
            emit(d->cor_name, d->folder, r.role, names, r.sizes, (r.required ? 1 : 0) | (r.shared ? 2 : 0), r.set);
        }
        if (d->romset) {
            emit(d->cor_name, d->folder, d->romset->role, d->romset->ext, d->romset->sizes, 1 | 4, 0);
        }
#ifdef TEST_APP_NEOGEO                                  // the TRX64U rows follow the Neo Geo's: only the Neo Geo's app (run.sh neogeoapp) emits them
        if (!strcmp(d->folder, "neogeo")) {
            emit_trx64u();
        }
#endif
    }
    return 0;
}
