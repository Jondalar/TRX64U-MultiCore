// T148 D7: writes the table of the ROM files each core needs, the one the host application's maintenance page reads (it cannot link the
// core application's descriptors). tests/coreapp/run.sh builds this against coreapp/src/table.cc and compares the output with the checked-in
// host-app/software/hostapp/romreq_table.inc: a changed RomSpec without a regenerated table is a red run.
//   gen_romreq > host-app/software/hostapp/romreq_table.inc
#include <stdio.h>
#include <string.h>
#include "table.cc"
#include "romset.h"

static void emit(const char *core, const char *folder, const char *role, const char *names, const uint32_t *sizes, int flags, int set)
{
    printf("    { \"%s\", \"%s\", \"%s\", \"%s\", { ", core, folder, role, names);
    for (int i = 0; i < 3; i++) {
        printf("%u%s", (unsigned)(sizes ? sizes[i] : 0), i < 2 ? ", " : "");
    }
    printf(" }, %d, %d },\n", flags, set);
}

int main()
{
    printf("// Generated by tests/coreapp/gen_romreq.cc from coreapp/src/table.cc - do not edit; tests/coreapp/run.sh compares it.\n");
    printf("// core = the manifest name, role, names = file names separated by '|' (a ROM set: the extension), sizes, flags (1 required,\n");
    printf("// 2 shared device ROM, 4 one file of the extension out of a set,\n");
    printf("// 8 a part of another ROM's image: bits 4 and up are that ROM's number in the core's rows, from 1), set = bit mask of the variants (desc.h)\n");
    for (const CoreDesc *const *p = core_table; *p; p++) {
        const CoreDesc *d = *p;
        for (int i = 0; i < d->nroms; i++) {
            const RomSpec &r = d->roms[i];
            char names[200] = "";
            for (int k = 0; k < ROM_NAMES_MAX && r.names[k]; k++) {
                if (k) {
                    strcat(names, "|");
                }
                strcat(names, r.names[k]);
            }
            emit(d->cor_name, d->folder, r.role, names, r.sizes, (r.required ? 1 : 0) | (r.shared ? 2 : 0) | (r.into ? 8 | (r.into << 4) : 0), r.set);
        }
        if (d->romset) {
            emit(d->cor_name, d->folder, d->romset->role, d->romset->ext, d->romset->sizes, 1 | 4, 0);
        }
    }
    return 0;
}
