#!/usr/bin/env python3
"""T189: writes the shelf coefficients into host/trx_tone.v (between COEF BEGIN/END; "check" only compares) (RBJ cookbook, S = 1, Fs = 48 kHz, double precision, Q2.16 (bass) / Q3.15 (treble) in 18 bit).
Bass = low shelf 200 Hz +6 dB, Treble = high shelf 4 kHz +6 dB (T189 D2). The feedback terms are stored negated (y = b0 x0 + b1 x1 + b2 x2 + na1 y1 + na2 y2)."""
import math, sys, os

FS = 48000.0

def shelf(kind, f0, db, S=1.0):
    A = 10 ** (db / 40.0)
    w = 2 * math.pi * f0 / FS
    cs, sn = math.cos(w), math.sin(w)
    al = sn / 2 * math.sqrt((A + 1 / A) * (1 / S - 1) + 2)
    r = 2 * math.sqrt(A) * al
    if kind == "low":
        b0 = A * ((A + 1) - (A - 1) * cs + r); b1 = 2 * A * ((A - 1) - (A + 1) * cs); b2 = A * ((A + 1) - (A - 1) * cs - r)
        a0 = (A + 1) + (A - 1) * cs + r;      a1 = -2 * ((A - 1) + (A + 1) * cs);     a2 = (A + 1) + (A - 1) * cs - r
    else:
        b0 = A * ((A + 1) + (A - 1) * cs + r); b1 = -2 * A * ((A - 1) + (A + 1) * cs); b2 = A * ((A + 1) + (A - 1) * cs - r)
        a0 = (A + 1) - (A - 1) * cs + r;       a1 = 2 * ((A - 1) - (A + 1) * cs);      a2 = (A + 1) - (A - 1) * cs - r
    return [b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0]

def q(x, sh):
    v = int(round(x * (1 << sh)))
    assert -131072 <= v <= 131071, x
    return v

out = ["// generated by host/sim/tone/gen_coeffs.py (T189): shelf coefficients, Bass Q2.16, Treble Q3.15, 18 bit signed. Do not edit."]
for name, kind, f0 in (("BASS", "low", 200.0), ("TREB", "high", 4000.0)):
    b0, b1, b2, a1, a2 = shelf(kind, f0, 6.0)
    for n, v in (("B0", b0), ("B1", b1), ("B2", b2), ("A1N", -a1), ("A2N", -a2)):
        out.append("localparam signed [17:0] %s_%s = %d;" % (name, n, q(v, 16 if name == "BASS" else 15)))
here = os.path.dirname(os.path.abspath(__file__))
dst = os.path.join(here, "..", "..", "trx_tone.v")
s = open(dst).read()
a = s.index("// COEF BEGIN\n") + len("// COEF BEGIN\n")
b = s.index("// COEF END")
new = "".join("    " + l + "\n" for l in out[1:])
if len(sys.argv) > 1 and sys.argv[1] == "check":
    sys.exit(0 if s[a:b] == new else "trx_tone.v coefficients differ from gen_coeffs.py")
open(dst, "w").write(s[:a] + new + s[b:])
print(new)
