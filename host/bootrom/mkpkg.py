#!/usr/bin/env python3
"""Write the boot ROM binary as Gideon's bootrom_pkg (vendor/gideon .../bootrom_8k.vhd
reads c_bootrom from it): 2048 little-endian 32-bit words."""
import sys

WORDS = 2048
data = open(sys.argv[1], "rb").read()
if len(data) > WORDS * 4:
    sys.exit(f"{sys.argv[1]}: {len(data)} bytes, the ROM holds {WORDS * 4}")
data = data.ljust(WORDS * 4, b"\0")
words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
rows = []
for r in range(0, WORDS, 8):
    rows.append("        " + ", ".join(f'X"{w:08x}"' for w in words[r:r + 8]))
with open(sys.argv[2], "w") as f:
    f.write("-- Generated by host/bootrom/mkpkg.py from the TRX64 boot ROM; do not edit.\n")
    f.write("library ieee;\nuse ieee.std_logic_1164.all;\n\npackage bootrom_pkg is\n")
    f.write("    type t_boot_data is array(natural range <>) of std_logic_vector(31 downto 0);\n\n")
    f.write(f"    constant c_bootrom : t_boot_data(0 to {WORDS - 1}) := (\n")
    f.write(",\n".join(rows))
    f.write("\n    );\nend package;\n")
