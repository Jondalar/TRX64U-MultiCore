#!/usr/bin/env python3
"""The one icon of every backup .cor the installer writes (T135 D8b): a circular arrow, "recovery". Writes recovery/logo-32.png and
recovery/icon.rgb565 (32 x 32, little-endian RGB565, 2,048 bytes, the .cor icon record 4) and update_trx's embedded copy
(vendor/gideon/software/application/update_u2p/recovery_icon.h, with --header PATH)."""
import math
import os
import struct
import sys
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
S = 16                        # supersampling
W = 32 * S
im = Image.new("RGB", (W, W), (0, 0, 0))
d = ImageDraw.Draw(im)
c, r, wd = W // 2, 11 * S, 4 * S
col = (120, 200, 255)
# the ring: 300 degrees, open at the upper right, running clockwise to the arrow head
box = [c - r, c - r, c + r, c + r]
d.arc(box, start=-50, end=250, fill=col, width=wd)
# arrow head at the end of the arc (angle 250 degrees measured clockwise from 3 o'clock = lower left going up), pointing along the tangent
a = math.radians(-50)
px, py = c + r * math.cos(a), c + r * math.sin(a)
tx, ty = -math.sin(a), math.cos(a)          # clockwise tangent at the arc's start: head sits at the start, pointing clockwise
nx, ny = math.cos(a), math.sin(a)
hl, hw = 7 * S, 6 * S
tip = (px + tx * hl, py + ty * hl)
d.polygon([tip, (px + nx * hw, py + ny * hw), (px - nx * hw, py - ny * hw)], fill=col)
im = im.resize((32, 32), Image.LANCZOS)
raw = bytearray()
q = Image.new("RGB", (32, 32))
for i, (rr, gg, bb) in enumerate(im.getdata()):
    v = ((rr >> 3) << 11) | ((gg >> 2) << 5) | (bb >> 3)
    raw += struct.pack("<H", v)
    q.putpixel((i % 32, i // 32), (((v >> 11) << 3) | (v >> 13), (((v >> 5) & 63) << 2) | ((v >> 9) & 3), ((v & 31) << 3) | ((v & 31) >> 2)))
os.makedirs(os.path.join(HERE, "recovery"), exist_ok=True)
q.save(os.path.join(HERE, "recovery", "logo-32.png"))
open(os.path.join(HERE, "recovery", "icon.rgb565"), "wb").write(bytes(raw))
if len(sys.argv) == 3 and sys.argv[1] == "--header":
    with open(sys.argv[2], "w") as f:
        f.write("// Generated by tools/core_logos/recovery.py (TRX64U-MultiCore): the icon of the backup .cor (T135 D8b), 32 x 32 RGB565 little endian.\n")
        f.write("static const unsigned char recovery_icon[2048] = {\n")
        for i in range(0, 2048, 16):
            f.write("    " + ", ".join("0x%02X" % b for b in raw[i:i + 16]) + ",\n")
        f.write("};\n")
print("recovery icon", len(raw), "bytes")
