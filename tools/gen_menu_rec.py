#!/usr/bin/env python3
"""T104.2 D10: coreapp/cores/trx64u/menu.toml -> coreapp/cores/trx64u/menu_rec.inc, the menu record the application carries for a start without a .cor.

  tools/gen_menu_rec.py            write the .inc (every name and binding of the menu is checked against tests/coreapp/golden/ops_trx64u.txt)
  tools/gen_menu_rec.py --check    do not write; exit 1 when the .inc on disk is not what the TOML compiles to (the lint stage)
  tools/gen_menu_rec.py --no-ops   skip the check against the export (only for the first run, before the export exists)
  tools/gen_menu_rec.py --bin out  also write the record itself (what tools/pack_import_cor.sh packs as record 6)
  --toml FILE, --ops FILE, --inc FILE   other inputs and output than the three above (the tests use them for their negative controls)

The record is the same bytes `descrec.py compile --ops` makes: this tool only wraps it in a C array.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import descrec  # noqa: E402

TOML = os.path.join(ROOT, "coreapp", "cores", "trx64u", "menu.toml")
INC = os.path.join(ROOT, "coreapp", "cores", "trx64u", "menu_rec.inc")
OPS = os.path.join(ROOT, "tests", "coreapp", "golden", "ops_trx64u.txt")


def render(blob):
    rows = [", ".join("0x%02X" % b for b in blob[i:i + 16]) for i in range(0, len(blob), 16)]
    return ("// Generated by tools/gen_menu_rec.py from menu.toml - do not edit; the lint stage and tests/coreapp/run.sh compare it with a fresh compile.\n"
            "static const uint8_t c64_menu_rec[] = {\n    " + ",\n    ".join(rows) + "\n};\n")


def opt(argv, name, default):
    return argv[argv.index(name) + 1] if name in argv else default


def main(argv):
    global INC
    check = "--check" in argv
    INC = opt(argv, "--inc", INC)
    toml = opt(argv, "--toml", TOML)
    ops = None if "--no-ops" in argv else open(opt(argv, "--ops", OPS)).read()
    try:
        blob = descrec.compile_checked(open(toml).read(), ops, what=os.path.basename(toml))
    except descrec.DescError as e:
        sys.exit("gen_menu_rec: %s" % e)
    text = render(blob)
    if "--bin" in argv:
        open(argv[argv.index("--bin") + 1], "wb").write(blob)
    if check:
        have = open(INC).read() if os.path.exists(INC) else ""
        if have != text:
            sys.exit("gen_menu_rec: %s is not what menu.toml compiles to; run tools/gen_menu_rec.py" % os.path.relpath(INC, ROOT))
        print("menu_rec.inc is current (%d bytes)" % len(blob))
        return
    open(INC, "w").write(text)
    print("wrote %s (%d bytes)" % (os.path.relpath(INC, ROOT), len(blob)))


if __name__ == "__main__":
    main(sys.argv[1:])
