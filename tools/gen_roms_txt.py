#!/usr/bin/env python3
"""ROMS.txt of a package or release (T148 D8): what every core needs in its own folder, and where the files can legally come from.

The files, names and sizes are the descriptors' RomSpecs (host-app/software/hostapp/romreq_table.inc, generated by tests/coreapp/gen_romreq.cc and
checked against the descriptors by tests/coreapp/run.sh); the cores without a RomSpec say what release_notes_mc.CORES says; the legal sources are
section 12.3 of the manual (docs/manual/12-roms.md). Nothing in it is typed twice.

  python3 tools/gen_roms_txt.py [-o ROMS.txt]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import core_toml  # noqa: E402
import release_notes_mc as N  # noqa: E402

TABLE = os.path.join(ROOT, "host-app", "software", "hostapp", "romreq_table.inc")
MANUAL = os.path.join(ROOT, "docs", "manual", "12-roms.md")
ROW = re.compile(r'^\s*\{\s*"((?:[^"\\]|\\.)*)",\s*"([^"]*)",\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",\s*\{\s*(\d+),\s*(\d+),\s*(\d+)\s*\},\s*(\d+),\s*(\d+)\s*\},\s*$')


def rows():
    out = []
    for line in open(TABLE, encoding="utf-8"):
        m = ROW.match(line)
        if m:
            core, folder, role, names, s1, s2, s3, flags, sets = m.groups()
            out.append(dict(core=core, role=role, names=names.split("|"), sizes=[int(x) for x in (s1, s2, s3) if int(x)],
                            flags=int(flags), set=int(sets)))
        elif line.strip() and not line.lstrip().startswith("//"):
            raise SystemExit("%s: a line that is no row: %r" % (TABLE, line))
    if not out:
        raise SystemExit("%s: no rows" % TABLE)
    return out


def cores():
    """(id, manifest name) of every core a user starts from a .cor, in the order of the descriptors."""
    out = []
    for name, _, t in core_toml.descriptors() + core_toml.large_descriptors():
        if not core_toml.in_pipeline(t) or t.get("flash_filler") or t.get("build_only") or name in [o[0] for o in out]:
            continue
        out.append((name, t.get("name", name)))
    return out


def left_out():
    """Lower-case names of what ROMS.txt does not list: a core with `pipeline = false` (T92 D-17e, by id and manifest name), a `build_only` core
    (never in a release; its RomSpec rows came out under a made-up folder, 2026-11-18; ci/package.sh still packs it for the board, whose ROMS.txt
    then has no section for it) and an imported core whose pin in release/imports/ says PIPELINE=false (ci/package.sh packs neither of the other two)."""
    out = set()
    for name, _, t in core_toml.descriptors() + core_toml.large_descriptors():
        if not core_toml.in_pipeline(t) or t.get("build_only"):
            out |= {name.lower(), str(t.get("name", name)).lower()}
    d = os.path.join(ROOT, "release", "imports")
    for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if f.endswith(".pin") and re.search(r"^PIPELINE=false", open(os.path.join(d, f), encoding="utf-8").read(), re.M):
            out.add(f[:-4].lower())
    return out


def legal():
    text = open(MANUAL, encoding="utf-8").read()
    a, b = text.index("## 12.3"), text.index("## 12.4")
    body = text[a:b].split("\n", 1)[1].replace("**", "").replace("`", "")
    paras = [p for p in body.strip().split("\n\n") if not N.bad_links(p)]       # a link that is not a legal source (12.3.5) stays in the manual
    return "\n\n".join("\n".join(l.rstrip() for l in p.split("\n")) for p in paras)


def render():
    allrows = rows()
    byname = {}
    off = left_out()
    for r in allrows:
        if r["core"].lower() in off:
            continue
        byname.setdefault(r["core"], []).append(r)
    notes = dict((c["id"], c) for c in N.CORES)
    lines = []
    w = lines.append
    w("ROM files - what each core needs")
    w("=" * 33)
    w("")
    w("This package contains no ROM, Kickstart or disk image. You bring your own.")
    w("Every core reads its ROM files from roms/ in its own folder, beside its .cor, and from nowhere else:")
    w("")
    w("    <medium>/cores/<name>.cor        the core (part of the release)")
    w("    <medium>/cores/<name>/roms/      its ROM files (made by the core at its first start)")
    w("")
    w("A file that lies in an old place (roms/<folder>/ on the flash, the sticks and the card, or a roms/ folder beside the .cor)")
    w("is copied there once, verified, when the core finds it missing. Nothing is shared between cores.")
    w("")
    shown = set()

    def rows_of(rs):
        for r in rs:
            size = " or ".join("{:,}".format(s) for s in r["sizes"]) + " bytes"
            if r["flags"] & 4:
                what = "any file %s of %s" % (r["names"][0], size)
            else:
                what = "%s  %s" % (" or ".join(r["names"]), size)
            if r["set"]:
                need = "needed for set " + "+".join(str(b + 1) for b in range(8) if r["set"] & (1 << b))
            elif r["flags"] & 1:
                need = "required"
            else:
                need = "optional"
            if r["flags"] & 2:
                need += ", a device ROM (each core has its own copy)"
            w("    %-24s %s  [%s]" % (r["role"] + ":", what, need))
        if any(r["set"] for r in rs):
            w("    (a core with sets starts when ONE complete set is there)")

    for cid, name in cores():
        w("%s  (cores/%s/roms/)" % (name, cid))
        rs = byname.get(name)
        shown.add(name)
        if rs:
            rows_of(rs)
        elif cid in notes:
            w("    %s  [%s]" % (notes[cid]["files"].replace("`", ""), notes[cid]["needed"]))
        else:
            w("    none")
        w("")
    for name in sorted(byname):                                       # a core with a RomSpec and no core.toml of its own (TRX64U, whose .cor is trx64u.cor)
        if name not in shown:
            w("%s  (cores/%s/roms/)" % (name, name.lower()))
            rows_of(byname[name])
            w("")
    if "trx64u" not in off:
        w("TRX64U, ROMs from the board's flash")
        w("    the ROMs that are in the board's flash (Kernal 8,192, Basic 8,192, Char 4,096 bytes); the core copies them into")
        w("    cores/trx64u/roms/ at its first start. Nothing to bring.")
        w("")
    w("Legal sources")
    w("-------------")
    w(legal())
    w("")
    return "\n".join(lines)


def main():
    a = sys.argv[1:]
    text = render()
    if a[:1] == ["-o"] and len(a) == 2:
        open(a[1], "w", encoding="utf-8").write(text)
    elif not a:
        sys.stdout.write(text)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
