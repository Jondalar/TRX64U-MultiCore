#!/usr/bin/env python3
"""T182 step 3c: the SuperCPU memory configuration table (VICE scpu64meminit.c) as a checked-in table and the Verilog ROM made from it.

  scpu_cfgtab.py [--vice <scpu64meminit.c>]   read the oracle, write cores/c64scpu/scpu_cfgtab.txt and cores/c64scpu/scpu_cfgtab.v
  scpu_cfgtab.py --from-txt                   no oracle: write only cores/c64scpu/scpu_cfgtab.v from the checked-in .txt
  scpu_cfgtab.py --check                      lint: the Verilog is what the .txt makes; and, when the oracle source is reachable (--vice, $SCPU_VICE_MEMINIT, or the
                                              usual path under ~/Development/C64/Tools/vice), the .txt is what the oracle says. Without the oracle that half is skipped
                                              and says so (the oracle is not in this repository).

The table: AREAS = 10 page ranges x 256 configuration entries; the entry index is {boot, dos, hw, !game, !exrom, loram, hiram, charen} (scpu64meminit.c
header). Each cell is one class of memory; the class numbers are the enum order of the oracle:
  R0 SRAM bank 0, R1 SRAM bank 1, RC internal C64 RAM, UM Ultimax, RL ROML, RH ROMH, IO I/O, CR character ROM, F8 EPROM (the SuperCPU ROM),
  KS kernal shadow, KT kernal trap, CO colour RAM, OP internal colour RAM.
Output module scpu_cfgtab: a LUT ROM (distributed) in front of the output register q (T248; it was a block RAM), a = {area[3:0], index[7:0]}, q = class of the address one clock later; scpu_area: page (address bits 15:8) -> area.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TXT = os.path.join(ROOT, "cores/c64scpu/scpu_cfgtab.txt")
VER = os.path.join(ROOT, "cores/c64scpu/scpu_cfgtab.v")
CLASSES = ["R0", "R1", "RC", "UM", "RL", "RH", "IO", "CR", "F8", "KS", "KT", "CO", "OP"]
DEFAULT_ORACLE = os.path.expanduser("~/Development/C64/Tools/vice/vice/src/scpu64/scpu64meminit.c")


def parse_oracle(path):
    src = open(path).read()
    m = re.search(r"enum\s*\{(.*?)\};", src, re.S)
    names = re.findall(r"^\s*([A-Z][A-Z0-9]),", m.group(1), re.M)
    assert names == CLASSES, names
    a = re.search(r"areas\[AREAS\]\[2\]\s*=\s*\{(.*?)\n\};", src, re.S)
    areas = [(int(x, 16), int(y, 16)) for x, y in re.findall(r"\{\s*0x([0-9a-f]+),\s*0x([0-9a-f]+)\s*\}", a.group(1))]
    c = re.search(r"config\[AREAS\]\[256\]\s*=\s*\n?\{(.*)\n\};", src, re.S)
    blocks = re.findall(r"\{\s*/\*[^*]*\*/(.*?)\}", c.group(1), re.S)
    assert len(blocks) == len(areas) == 10, (len(blocks), len(areas))
    cfg = []
    for b in blocks:
        cells = re.findall(r"\b([A-Z][A-Z0-9])\b", b)
        assert len(cells) == 256 and all(x in CLASSES for x in cells), len(cells)
        cfg.append(cells)
    return areas, cfg


def write_txt(areas, cfg):
    out = ["# T182 step 3c: the SuperCPU memory configuration table, generated by tools/scpu_cfgtab.py from scpu64meminit.c. Do not edit.",
           "# classes: " + " ".join("%s=%d" % (n, i) for i, n in enumerate(CLASSES)),
           "# area <n> <first page> <last page>, then 16 rows of 16 cells: row r column c is the entry index 16 r + c = {boot,dos,hw,!game,!exrom,loram,hiram,charen}"]
    for i, ((lo, hi), cells) in enumerate(zip(areas, cfg)):
        out.append("area %d %02x %02x" % (i, lo, hi))
        for r in range(16):
            out.append(" ".join(cells[16 * r:16 * r + 16]))
    return "\n".join(out) + "\n"


def read_txt(text):
    areas, cfg, cur = [], [], None
    for ln in text.splitlines():
        if not ln or ln.startswith("#"):
            continue
        if ln.startswith("area "):
            p = ln.split()
            areas.append((int(p[2], 16), int(p[3], 16)))
            cur = []
            cfg.append(cur)
        else:
            cur.extend(ln.split())
    assert len(areas) == 10 and all(len(c) == 256 for c in cfg)
    return areas, cfg


def make_verilog(areas, cfg):
    v = ["// T182 step 3c: GENERATED by tools/scpu_cfgtab.py from cores/c64scpu/scpu_cfgtab.txt (the oracle: VICE scpu64meminit.c). Do not edit; `python3 tools/scpu_cfgtab.py --check` is in ci/lint.sh.",
         "// class numbers: " + " ".join("%s=%d" % (n, i) for i, n in enumerate(CLASSES)),
         "`timescale 1ns / 1ps",
         "module scpu_area (input wire [7:0] page, output reg [3:0] area);",
         "  always @(*) begin"]
    for i, (lo, hi) in enumerate(areas):
        v.append("    %s (page >= 8'h%02x && page <= 8'h%02x) area = 4'd%d;" % ("if" if i == 0 else "else if", lo, hi, i))
    v += ["    else area = 4'd15;", "  end", "endmodule", "",
          "// a = {area, index}; q is the class one clock later: a LUT ROM in front of the output register q (T248; it was a block RAM)",
          "module scpu_cfgtab (input wire clk, input wire [11:0] a, output reg [3:0] q);",
          "  (* rom_style = \"distributed\" *) reg [3:0] t [0:4095];",
          "  integer i;",
          "  initial begin",
          "    for (i = 0; i < 4096; i = i + 1) t[i] = 4'd0;"]
    for ai, cells in enumerate(cfg):
        j = 0
        while j < 256:
            k = j
            while k + 1 < 256 and cells[k + 1] == cells[j]:
                k += 1
            if cells[j] != "R0":
                if k == j:
                    v.append("    t[12'h%x%02x] = 4'd%d;" % (ai, j, CLASSES.index(cells[j])))
                else:
                    v.append("    for (i = 12'h%x%02x; i <= 12'h%x%02x; i = i + 1) t[i] = 4'd%d;" % (ai, j, ai, k, CLASSES.index(cells[j])))
            j = k + 1
    v += ["  end", "  always @(posedge clk) q <= t[a];", "endmodule", ""]
    return "\n".join(v)


def main():
    argv = sys.argv[1:]
    check = "--check" in argv
    oracle = None
    if "--vice" in argv:
        oracle = argv[argv.index("--vice") + 1]
    oracle = oracle or os.environ.get("SCPU_VICE_MEMINIT") or (DEFAULT_ORACLE if os.path.exists(DEFAULT_ORACLE) else None)
    if "--from-txt" in argv:
        areas, cfg = read_txt(open(TXT).read())
        open(VER, "w").write(make_verilog(areas, cfg))
        print("wrote", VER)
        return 0
    if not check:
        if not oracle:
            sys.exit("no oracle source: --vice <scpu64meminit.c>")
        areas, cfg = parse_oracle(oracle)
        open(TXT, "w").write(write_txt(areas, cfg))
        open(VER, "w").write(make_verilog(areas, cfg))
        print("wrote", TXT, VER)
        return 0
    rc = 0
    areas, cfg = read_txt(open(TXT).read())
    if open(VER).read() != make_verilog(areas, cfg):
        print("FAIL: cores/c64scpu/scpu_cfgtab.v is not what scpu_cfgtab.txt makes (run tools/scpu_cfgtab.py --from-txt)")
        rc = 1
    if oracle and os.path.exists(oracle):
        oa, oc = parse_oracle(oracle)
        if write_txt(oa, oc) != open(TXT).read():
            print("FAIL: scpu_cfgtab.txt is not what the oracle %s says" % oracle)
            rc = 1
        else:
            print("ok: the table equals the oracle", oracle)
    else:
        print("note: oracle source not reachable here, only the .txt -> .v half was checked")
    if rc == 0:
        print("ok: cores/c64scpu/scpu_cfgtab.v is what scpu_cfgtab.txt makes")
    return rc


if __name__ == "__main__":
    sys.exit(main())
