#!/usr/bin/env python3
"""T260: generate the diag core's pin-table files from cores/diag/rtl/pins.toml and check the top against it.

  python3 tools/diag_pins_gen.py            write the generated files
  python3 tools/diag_pins_gen.py --check    lint: the generated files are current, the table equals the connector ports of
                                            cores/diag/mono/top.v (every top port is a bank pin or excluded, direction and vector
                                            range agree), every drivable pin is wired in the top, ROM geometry holds (S3)
  python3 tools/diag_pins_gen.py --dump     one line per pin (index name dir class flags group idle), what the ROM bench compares with
"""
import os, re, sys, tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "cores/diag/rtl/pins.toml")
TOP = os.path.join(ROOT, "cores/diag/mono/top.v")
OUT = {
    "tab": os.path.join(ROOT, "cores/diag/rtl/diag_pintab.vh"),
    "rom": os.path.join(ROOT, "cores/diag/rtl/diag_pinrom.v"),
    "dgin": os.path.join(ROOT, "cores/diag/mono/diag_dgin.vh"),
}
DIR = {"in": 0, "out": 1, "inout": 2}
CLS = {"none": 0, "od": 1, "pull": 2, "push": 3, "pz": 4, "pzh": 5}
GRP = {"slot": 0, "joy": 1, "paddle": 2, "c2n": 3, "iec": 4, "ui": 5, "led": 6, "av": 7, "misc": 8}
FLG = ("guard", "inv", "buf", "pwr", "gen", "host")
HDR = "// GENERATED by tools/diag_pins_gen.py from cores/diag/rtl/pins.toml (T260) - do not edit; `diag_pins_gen.py --check` finds it stale.\n"


def load():
    with open(SRC, "rb") as f:
        d = tomllib.load(f)
    pins = d["pin"]
    errs = []
    for i, p in enumerate(pins):
        if p["index"] != i:
            errs.append(f"pin {p['name']}: index {p['index']} is not its position {i}")
        if len(p["name"]) > 15:
            errs.append(f"pin {p['name']}: name longer than 15 characters")
        if p["dir"] not in DIR or p["class"] not in CLS or p["group"] not in GRP:
            errs.append(f"pin {p['name']}: unknown dir / class / group")
    if len({p["name"] for p in pins}) != len(pins):
        errs.append("duplicate pin names")
    if d["bank"]["count"] != len(pins):
        errs.append(f"[bank] count {d['bank']['count']} but {len(pins)} pins")
    if len(pins) > 127:
        errs.append("more than 127 pins: the 7 bit index has no room for the unused lane code 0x7F")
    for p in pins:
        if p["class"] in ("od", "pull", "push", "pz", "pzh") and (p.get("pwr") or p.get("gen")):
            errs.append(f"pin {p['name']}: a power or generator pin must not be drivable")
        if p["class"] != "none" and p["dir"] == "in":
            errs.append(f"pin {p['name']}: an input is not drivable")
    return d, pins, errs


def rom_entry(p):
    b = bytearray(32)
    nm = p["name"].encode("ascii")
    b[0:len(nm)] = nm
    b[16] = DIR[p["dir"]]
    b[17] = CLS[p["class"]]
    b[18] = sum(1 << k for k, f in enumerate(FLG) if p.get(f))
    b[19] = GRP[p["group"]]
    b[20] = p.get("idle", 2)
    return b


def gen_tab(pins):
    o = [HDR, f"localparam DG_N = {len(pins)};          // pins in the bank (register 080)\n"]
    for p in pins:
        o.append(f"localparam [6:0] IX_{p['name']} = 7'd{p['index']};\n")
    o.append("// {guard, class[2:0]} of a pin: class 0 none, 1 od, 2 pull, 3 push, 4 pz, 5 pzh; an index past the bank = 0\n")
    o.append("function [3:0] dgpin_cls(input [6:0] i);\n    case (i)\n")
    for p in pins:
        g = 1 if p.get("guard") else 0
        o.append(f"    7'd{p['index']}: dgpin_cls = {{1'b{g}, 3'd{CLS[p['class']]}}};\n")
    o.append("    default: dgpin_cls = 4'd0;\n    endcase\nendfunction\n")
    return "".join(o)


def gen_rom(pins):
    o = [HDR, "// The pin-table ROM: 128 entries of 32 bytes (register 0C0-0DF shows the entry of PIN_IDX). a = {index[6:0], byte[4:0]}, one clock read.\n",
         "`timescale 1ns / 1ps\nmodule diag_pinrom (\n    input  wire        clk,\n    input  wire [11:0] a,\n    output reg  [7:0]  q\n);\n",
         "    reg [7:0] rom [0:4095];\n    integer k;\n    initial begin\n        for (k = 0; k < 4096; k = k + 1) rom[k] = 8'h00;\n"]
    for p in pins:
        e = rom_entry(p)
        for k, v in enumerate(e):
            if v:
                o.append(f"        rom[{p['index'] * 32 + k}] = 8'h{v:02X};\n")
    o.append("    end\n    always @(posedge clk) q <= rom[a];\nendmodule\n")
    return "".join(o)


def src_of(p):
    if p.get("src"):
        return p["src"]
    return f"{p['port']}[{p['bit']}]" if "bit" in p else p["port"]


def gen_dgin(pins):
    o = [HDR, "// included in mono/top.v: the snapshot input of the diag bank, dg_in[index] = the net the top reads for that pin (the ball for an input, the drive for an output)\n"]
    for p in pins:
        o.append(f"assign dg_in[IX_{p['name']}] = {src_of(p)};\n")
    for i in range(len(pins), 128):
        o.append(f"assign dg_in[{i}] = 1'b0;\n")
    return "".join(o)


def top_ports():
    txt = open(TOP).read()
    m = re.search(r"\bmodule\s+top\b.*?\)\s*\(\s*(.*?)\n\);", txt, re.S)
    hdr = re.sub(r"//[^\n]*", "", m.group(1))
    ports, cur = {}, None
    for part in hdr.split(","):
        part = part.strip()
        if not part:
            continue
        mm = re.match(r"(input|output|inout)\s+(?:wire\s+)?(?:\[(\d+)\s*:\s*(\d+)\]\s*)?(\w+)\s*$", part)
        if mm:
            cur = (mm.group(1), int(mm.group(2)) if mm.group(2) else None, int(mm.group(3)) if mm.group(3) else None)
            ports[mm.group(4)] = cur
        elif re.match(r"^\w+$", part) and cur:
            ports[part] = cur
        else:
            raise SystemExit(f"top.v port list: cannot parse '{part}'")
    return ports


def check(d, pins):
    errs = []
    ports = top_ports()
    excl = {n for lst in d["excluded"].values() for n in lst}
    tp = {p["port"] for p in pins}
    for p in pins:
        t = ports.get(p["port"])
        if t is None:
            errs.append(f"{p['name']}: top.v has no port {p['port']}")
            continue
        if t[0] != {"in": "input", "out": "output", "inout": "inout"}[p["dir"]]:
            errs.append(f"{p['name']}: table says {p['dir']}, top.v declares {p['port']} as {t[0]}")
        hi, lo = t[1], t[2]
        if "bit" in p:
            if hi is None or not (lo <= p["bit"] <= hi):
                errs.append(f"{p['name']}: bit {p['bit']} is outside the range of {p['port']}")
        elif hi is not None:
            errs.append(f"{p['name']}: {p['port']} is a vector in top.v, the table gives no bit")
    for nm, t in ports.items():
        if nm not in tp and nm not in excl:
            errs.append(f"top.v port {nm} is neither in the bank nor excluded")
        if nm in tp and nm in excl:
            errs.append(f"port {nm} is both in the bank and excluded")
    for nm in excl:
        if nm not in ports:
            errs.append(f"excluded port {nm} is not a top.v port")
    for port in sorted(tp):
        t = ports.get(port)
        if t and t[1] is not None:
            bits = sorted(p["bit"] for p in pins if p["port"] == port)
            if bits != list(range(t[2], t[1] + 1)):
                errs.append(f"{port}: the bank covers bits {bits}, top.v declares [{t[1]}:{t[2]}]")
    # the top wires the bank: dg_in comes from the generated include, every drivable pin is named (or its vector base) outside comments
    code = re.sub(r"//[^\n]*", "", open(TOP).read())
    if "`include \"diag_dgin.vh\"" not in code or "`include \"diag_pintab.vh\"" not in code:
        errs.append("top.v does not include diag_pintab.vh and diag_dgin.vh")
    for p in pins:
        if p["class"] == "none":
            continue
        base = [q for q in pins if q["port"] == p["port"] and q.get("bit", 0) == min(r.get("bit", 0) for r in pins if r["port"] == p["port"])][0]
        if f"IX_{p['name']}" not in code and f"IX_{base['name']}" not in code:
            errs.append(f"{p['name']}: drivable but top.v names neither IX_{p['name']} nor the vector base IX_{base['name']}")
        if "bit" in p and base is not p and p["index"] != base["index"] + p["bit"] - base["bit"]:
            errs.append(f"{p['name']}: not contiguous with its vector base, a loop over IX_{base['name']} + n would miss it")
    for k, text in (("tab", gen_tab(pins)), ("rom", gen_rom(pins)), ("dgin", gen_dgin(pins))):
        try:
            cur = open(OUT[k]).read()
        except OSError:
            cur = None
        if cur != text:
            errs.append(f"{os.path.relpath(OUT[k], ROOT)} is stale: run python3 tools/diag_pins_gen.py")
    return errs


def main():
    d, pins, errs = load()
    if "--dump" in sys.argv:
        for p in pins:
            e = rom_entry(p)
            print(f"{p['index']} {p['name']} {e[16]} {e[17]} {e[18]} {e[19]} {e[20]}")
        return 0
    if "--check" in sys.argv:
        errs += check(d, pins)
        for e in errs:
            print("FAIL diag pins:", e)
        if errs:
            return 1
        print(f"ok   diag pins: {len(pins)} pins, the generated files are current, the table equals the connector ports of cores/diag/mono/top.v")
        return 0
    if errs:
        for e in errs:
            print("FAIL diag pins:", e)
        return 1
    for k, text in (("tab", gen_tab(pins)), ("rom", gen_rom(pins)), ("dgin", gen_dgin(pins))):
        open(OUT[k], "w").write(text)
        print("wrote", os.path.relpath(OUT[k], ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
