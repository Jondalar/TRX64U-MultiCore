#!/usr/bin/env python3
"""T239.3 D32: coreapp/base_ui.toml (the SDK's base UI TOML) -> coreapp/src/base_ui.inc, the table of routes and places menutree.cc includes, and coreapp/src/base_rows.inc, the table of
the rows (label, key, kind, values, default, pick) menubuild.cc includes.

  tools/gen_base_ui.py            write both .inc files (the TOML is compiled by tools/descrec.py into the record a core's UI TOML carries, read back, and written as C++ initializers)
  tools/gen_base_ui.py --check    do not write; exit 1 when an .inc on disk is not what the TOML compiles to (the lint stage)
  tools/gen_base_ui.py --ops FILE also check every operation of a place against the application's export (tests/coreapp/golden/ops_trx64u.txt lists them)
  --toml FILE, --inc FILE, --rows FILE   other input and output than the three above (the tests use them)

The base's own record must be whole: every place that names a route finds it in this file (a core's place may name a base route, the base's own may not name an absent one), and every row
has a place (by its operation, and its key when the place names one) - a row nobody places would stand nowhere.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import descrec  # noqa: E402

TOML = os.path.join(ROOT, "coreapp", "base_ui.toml")
INC = os.path.join(ROOT, "coreapp", "src", "base_ui.inc")
ROWS = os.path.join(ROOT, "coreapp", "src", "base_rows.inc")


def cstr(s):
    return "0" if s is None else '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def render(rec):
    routes, places = rec["group_route"], rec["place"]
    out = ["// Generated by tools/gen_base_ui.py from coreapp/base_ui.toml - do not edit; the lint stage compares it with a fresh compile.",
           "static const UiPlace g_base_place = {",
           "    {"]
    for r in routes:
        out.append("        { %s, %s, %s, %s, %s, %s }," % (cstr(r["group"]), cstr(r["area"]), cstr(r["tab"]), cstr(r["heading"]), cstr(r.get("label")),
                                                          "true" if r.get("page") else "false"))
    out.append("    }, %d," % len(routes))
    out.append("    {")
    for p in places:
        order = "UI_NO_ORDER" if "order" not in p else str(p["order"])
        out.append("        { %s, %s, %s, %s, %s }," % (cstr(p["op"]), cstr(p.get("key")), cstr(p.get("route")), cstr(p.get("group")), order))
    out.append("    }, %d" % len(places))
    out.append("};")
    return "\n".join(out) + "\n"


def render_rows(rows):
    """The rows as C++ initializers of BaseRow (menubuild.h). A text row's default is the empty text (the record holds a blank, which it has no empty strings for)."""
    out = ["// Generated by tools/gen_base_ui.py from coreapp/base_ui.toml - do not edit; the lint stage compares it with a fresh compile."]
    names, lists = {}, []
    for r in rows:
        text = r["when"] in ("text", "secret")
        vals = tuple("" if text and v == " " else v for v in r["values"])
        if vals not in names:
            names[vals] = "g_base_values_%d" % len(names)
            lists.append((names[vals], vals))
    for nm, vals in lists:
        out.append("static const char *const %s[] = { %s };" % (nm, ", ".join(cstr(v) for v in vals)))
    out.append("static const BaseRow g_base_row[] = {")
    for r in rows:
        text = r["when"] in ("text", "secret")
        vals = tuple("" if text and v == " " else v for v in r["values"])
        out.append("    { %s, %s, %s, %d, %d, %d, %d, %s, %s, %s }," % (cstr(r["key"]), cstr(r["label"]), names[vals], len(vals), r["default"], r["base"],
                                                                     {"live": 0, "text": 1, "secret": 2}[r["when"]], cstr(r["apply"]), cstr(r["show_state"]), cstr(r["pick"])))
    out.append("};")
    out.append("static const int g_base_nrows = %d;" % len(rows))
    return "\n".join(out) + "\n"


def opt(argv, name, default):
    return argv[argv.index(name) + 1] if name in argv else default


def main(argv):
    toml, inc, rows_inc = opt(argv, "--toml", TOML), opt(argv, "--inc", INC), opt(argv, "--rows", ROWS)
    try:
        ops = open(argv[argv.index("--ops") + 1]).read() if "--ops" in argv else None
        blob = descrec.compile_checked(open(toml).read(), ops, what=os.path.basename(toml), app_base=True)
        rec = descrec.parse_desc(blob)
        if not rec.get("group_route") or not rec.get("place"):
            raise descrec.DescError("the base UI TOML needs [[group_route]] and [[place]]")
        names = {r["group"] for r in rec["group_route"]}
        for p in rec["place"]:
            if p.get("route") and p["route"] not in names:
                raise descrec.DescError('place "%s": route "%s" is not a [[group_route]] of the base' % (p["op"], p["route"]))
            if not p.get("route") or not p.get("group") or "order" not in p:
                raise descrec.DescError('place "%s": the base places every row completely (route, group and order)' % p["op"])
        rows = rec["cset"]
        if not rows:
            raise descrec.DescError("the base UI TOML needs [[core_setting]] rows")
        for r in rows:
            if r["file"] or r["lock_state"]:
                raise descrec.DescError('row "%s": a file row or a locked row is a core\'s, not the base\'s' % r["key"])
            if r["when"] not in ("live", "text", "secret"):
                raise descrec.DescError('row "%s": the base has live, text and secret rows (when = "%s")' % (r["key"], r["when"]))
            if not any(p["op"] == r["apply"] and (not p.get("key") or p["key"].lower() == r["key"].lower()) for p in rec["place"]):
                raise descrec.DescError('row "%s" (%s) has no [[place]]' % (r["key"], r["apply"]))
    except descrec.DescError as e:
        sys.exit("gen_base_ui: %s" % e)
    text, rtext = render(rec), render_rows(rows)
    if "--check" in argv:
        for path, want in ((inc, text), (rows_inc, rtext)):
            have = open(path).read() if os.path.exists(path) else ""
            if have != want:
                sys.exit("gen_base_ui: %s is not what base_ui.toml compiles to; run tools/gen_base_ui.py" % os.path.relpath(path, ROOT))
        print("base_ui.inc and base_rows.inc are current (%d routes, %d places, %d rows)" % (len(rec["group_route"]), len(rec["place"]), len(rows)))
        return
    open(inc, "w").write(text)
    open(rows_inc, "w").write(rtext)
    print("wrote %s and %s (%d routes, %d places, %d rows)" % (os.path.relpath(inc, ROOT), os.path.relpath(rows_inc, ROOT), len(rec["group_route"]), len(rec["place"]), len(rows)))


if __name__ == "__main__":
    main(sys.argv[1:])
