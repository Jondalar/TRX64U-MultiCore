#!/usr/bin/env python3
"""T209 D10: the boot menu's state pictograms as A8 masks (22 x 22, stride 24): a disc with the glyph cut out; the host app tints them
(green / yellow / red). Writes host-app/software/hostapp/menu_pictos.h."""
import sys
from PIL import Image, ImageDraw

N, S, STRIDE = 22, 8, 24
def mask(kind):
    big = N * S
    disc = Image.new("L", (big, big), 0)
    ImageDraw.Draw(disc).ellipse((0, 0, big - 1, big - 1), fill=255)
    gl = Image.new("L", (big, big), 0)
    g = ImageDraw.Draw(gl)
    w = int(2.4 * S)
    p = lambda x, y: (x * S, y * S)
    if kind == 0:      # check mark
        g.line([p(5.6, 11.4), p(9.6, 15.4), p(16.6, 7.0)], fill=255, width=w, joint="curve")
    elif kind == 1:    # question mark
        g.arc((p(6.8, 4.6)[0], p(6.8, 4.6)[1], p(15.2, 12.0)[0], p(15.2, 12.0)[1]), 180, 20, fill=255, width=w)
        g.line([p(14.2, 9.2), p(11.0, 12.4), p(11.0, 13.8)], fill=255, width=w, joint="curve")
        g.ellipse((p(9.7, 15.9)[0], p(9.7, 15.9)[1], p(12.3, 18.5)[0], p(12.3, 18.5)[1]), fill=255)
    else:              # cross
        g.line([p(7.0, 7.0), p(15.0, 15.0)], fill=255, width=w)
        g.line([p(15.0, 7.0), p(7.0, 15.0)], fill=255, width=w)
    out = Image.new("L", (big, big), 0)
    out.paste(disc, (0, 0))
    out.paste(0, (0, 0), gl)
    return out.resize((N, N), Image.LANCZOS)

o = ["// generated by tools/gen_menu_pictos.py (T209 D10): do not edit", "#pragma once", "#include <stdint.h>", ""]
for k, nm in enumerate(["OK", "CHECK", "BAD"]):
    m = mask(k)
    o.append("static const uint8_t PICTO_%s[%d * %d] = {" % (nm, STRIDE, N))
    for y in range(N):
        row = [m.getpixel((x, y)) for x in range(N)] + [0] * (STRIDE - N)
        o.append("    " + ", ".join(str(v) for v in row) + ",")
    o.append("};")
open(sys.argv[1] if len(sys.argv) > 1 else "host-app/software/hostapp/menu_pictos.h", "w").write("\n".join(o) + "\n")
