#!/usr/bin/env python3
"""T115 D7: the built-in logos of the host app's .cfw rows as C arrays.
   gen_cfw_icons.py            writes host-app/software/hostapp/cfw_icons.h
   gen_cfw_icons.py --check    the checked-in header must be what the sources give now (negative controls run first)
Sources are the 2048-byte RGB565 files T114 makes; the header carries the same bytes, so a changed logo is one regenerate away."""
import os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "host-app", "software", "hostapp", "cfw_icons.h")
SOURCES = [("GIDEON", "tools/core_logos/u64/icon.rgb565"),
           ("TRX64", "tools/core_logos/trx64/icon.rgb565"),
           ("GENERIC", "tools/core_logos/firmware/icon.rgb565")]


def render(read):
    out = ["// Generated by tools/gen_cfw_icons.py from the T114 logo files; do not edit. Checked by `gen_cfw_icons.py --check`.",
           "#ifndef HOST_CFW_ICONS_H", "#define HOST_CFW_ICONS_H", "#include <stdint.h>", ""]
    for name, rel in SOURCES:
        data = read(rel)
        if len(data) != 2048:
            raise SystemExit("%s: %d bytes, expected 2048" % (rel, len(data)))
        out.append("// %s" % rel)
        out.append("static const uint8_t CFW_ICON_%s[2048] = {" % name)
        for i in range(0, 2048, 16):
            out.append("    " + ",".join("0x%02X" % b for b in data[i:i + 16]) + ",")
        out.append("};")
        out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def read_file(rel):
    with open(os.path.join(ROOT, rel), "rb") as f:
        return f.read()


if "--check" in sys.argv:
    # controls: a source one byte short must be refused, a changed byte must change the text
    try:
        render(lambda rel: read_file(rel)[:-1])
        sys.exit("control failed: a short source was accepted")
    except SystemExit as e:
        if "expected 2048" not in str(e):
            raise
    good = render(read_file)
    if render(lambda rel: bytes([read_file(rel)[0] ^ 1]) + read_file(rel)[1:]) == good:
        sys.exit("control failed: a changed byte left the header unchanged")
    if not os.path.exists(OUT) or open(OUT).read() != good:
        sys.exit("cfw_icons.h differs from the logo files: run tools/gen_cfw_icons.py")
    print("cfw_icons.h matches the logo files; controls failed as required")
else:
    with open(OUT, "w") as f:
        f.write(render(read_file))
