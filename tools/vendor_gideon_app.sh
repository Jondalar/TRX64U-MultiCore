#!/bin/sh
# The software half of vendor/gideon (our own copy of Gideon's 1541ultimate, T120, Alex 2026-11-01): what host-app/ and coreapp/ compile,
# the update_trx updater (tools/make_update.sh) builds from, and the host tests read. Run by tools/gideon_sources.sh after
# tools/vendor_gideon.sh (which makes the VHDL half and VENDOR.md and is part of the gateware key, so it stays as it is).
# Usage: tools/vendor_gideon_app.sh <1541ultimate checkout>     (adds to vendor/gideon, removes nothing)
#
# Taken: the files of tools/gideon_app.list (one path per line: the files the compiler and the tests open) and the third-party trees
# below, whole. None of them carries the clause "not supposed to be used in other projects without written permission"; the script
# stops if one ever does. VENDOR.md gets the commits and the licence note.
set -e
src=${1:?1541ultimate checkout}
here=$(cd "$(dirname "$0")/.." && pwd)
dst=$here/vendor/gideon
[ -f "$dst/VENDOR.md" ] || { echo "run tools/vendor_gideon.sh first" >&2; exit 1; }

app_trees="
software/lvgl
software/lwip/src
software/lwip/COPYING
software/FreeRTOS/Source
software/FreeRTOS/License
software/chan_fat/ff14/source
software/chan_fat/ff14/LICENSE.txt
software/chan_fat/full
software/chan_fat/pc
software/chan_fat/tiny_ro
software/httpd/c-version
software/httpd/LICENSE.md
"
for f in $(grep -v '^#' "$here/tools/gideon_app.list") $app_trees; do
  [ -e "$src/$f" ] || { echo "$f: not in the checkout" >&2; exit 1; }
  if [ -d "$src/$f" ]; then
    if grep -rIli "without written permission" "$src/$f" >/dev/null 2>&1; then
      echo "$f: restricted licence, not vendored" >&2
      exit 1
    fi
    mkdir -p "$dst/$f"
    cp -R "$src/$f/." "$dst/$f/"
    find "$dst/$f" -name '.git*' -prune -exec rm -rf {} +
  else
    if grep -qi "without written permission" "$src/$f"; then
      echo "$f: restricted licence, not vendored" >&2
      exit 1
    fi
    mkdir -p "$dst/$(dirname "$f")"
    cp "$src/$f" "$dst/$f"
  fi
done

# Our changes to the first-party files (tools/patches/gideon-app/*.patch, paths relative to vendor/gideon): T184 D4, the WiFi driver fixes of the fork
# omnicron-c64/ultimate-community-edition f7f665ab. They apply to the files as copied above; a patch that does not apply stops the script.
for p in "$here"/tools/patches/gideon-app/*.patch; do
  [ -e "$p" ] || continue
  patch -s -p1 -d "$dst" < "$p" || { echo "$p: does not apply to the copied files" >&2; exit 1; }
done

# LVGL's scripts/ are Python tools of its own build, not read by anything here (and the repository's ruff would lint them)
rm -rf "$dst/software/lvgl/scripts"

# VENDOR.md: vendor_gideon.sh wrote it for the submodule; this copy has none, and has more commits and files
perl -0pi -e 's/Generated by `tools\/gideon_sources.sh` from the submodule apps\/ultimate\. Do not edit here: change upstream or add a patch in tools\/patches\/gideon\./Our own copy (T120, Alex 2026-11-01), kept in git, no submodule behind it. Made by `tools\/gideon_sources.sh <1541ultimate checkout>` (tools\/vendor_gideon.sh, tools\/vendor_gideon_app.sh). Do not edit here: renew the copy from upstream or add a patch in tools\/patches\/gideon./' "$dst/VENDOR.md"
grep -q "Our own copy" "$dst/VENDOR.md" || { echo "VENDOR.md: the generated sentence is not there any more, fix tools/vendor_gideon_app.sh" >&2; exit 1; }
{
  echo
  echo "Software (tools/vendor_gideon_app.sh; the list is tools/gideon_app.list, the third-party trees come whole):"
  echo
  echo "| repository | commit |"
  echo "|---|---|"
  echo "| software/lwip (own repository in the checkout) | $(git -C "$src/software/lwip" rev-parse HEAD) |"
  echo "| software/httpd (own repository in the checkout) | $(git -C "$src/software/httpd" rev-parse HEAD) |"
  echo
  echo "software/, tools/*.c and Makefile, target/, roms/: what host-app/ and coreapp/ compile (host-app/target Makefiles, ci/trxapps.sh), the update_trx updater"
  echo "(tools/make_update.sh) and the host tests (tests/hostapp, tests/coreapp) read. host-app/software/ holds the patched copies of the first-party files"
  echo "(tools/hostapp_vendor.py, host-app/patches) made from here. software/lvgl (MIT), software/lwip (BSD), software/FreeRTOS (MIT), software/chan_fat"
  echo "(FatFs licence) and software/httpd keep their own licences next to their files; the rest is GPL-3.0 (LICENSE.txt). No software file carries the restricted clause."
  echo
  echo "Changed after copying (tools/patches/gideon-app, applied by the script): software/io/wifi/{wifi,wifi_cmd}.{cc,h}, software/io/network/network_esp32.{cc,h},"
  echo "software/u64ctrl/main/rpc_calls.h, and the new software/io/wifi/{wifi_reply,wifi_scan_result,wifi_connection_feedback}.h - T184 D4, the driver fixes of"
  echo "https://github.com/omnicron-c64/ultimate-community-edition at f7f665ab (GPL-3.0, like this tree); each changed file says so in its first line."
} >> "$dst/VENDOR.md"
echo "software added to $dst"
