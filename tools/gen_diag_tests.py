#!/usr/bin/env python3
"""T175: cores/diag/sd/tests/*.toml -> coreapp/cores/portdiag_tests.inc, the example tests the diag core app writes into /SD/cores/diag/tests
on its first start (never over a file that is there).

  tools/gen_diag_tests.py            write the .inc
  tools/gen_diag_tests.py --check    do not write; exit 1 when the .inc on disk is not what the files give (the lint stage)
"""
import hashlib
import os
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "cores", "diag", "sd", "tests")
OLD = os.path.join(ROOT, "cores", "diag", "superseded")     # earlier shipped texts <name>.v<N>.toml: the app replaces a file only when it equals one
INC = os.path.join(ROOT, "coreapp", "cores", "portdiag_tests.inc")


def raw_deflate(data):
    c = zlib.compressobj(9, zlib.DEFLATED, -15, 9)     # a raw deflate stream: coreapp/src/diagtest.cc inflates it (dt_inflate)
    return c.compress(data) + c.flush()


def c_bytes(data):
    rows = []
    for i in range(0, len(data), 24):
        rows.append(",".join("%d" % b for b in data[i:i + 24]))
    return ",\n        ".join(rows)


def fnv64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def render():
    names = sorted(f for f in os.listdir(SRC) if f.endswith(".toml"))
    h = hashlib.sha256()
    for n in names:
        h.update(n.encode() + b"\0" + open(os.path.join(SRC, n), "rb").read())
    for n in (sorted(f for f in os.listdir(OLD) if f.endswith(".toml")) if os.path.isdir(OLD) else []):
        h.update(n.encode() + b"\0" + open(os.path.join(OLD, n), "rb").read())
    s = ("// sources sha256 %s\n" % h.hexdigest()) + ("// Generated by tools/gen_diag_tests.py from cores/diag/sd/tests/*.toml - do not edit; the lint stage compares it with a fresh run.\n"
         "// The texts are raw deflate streams (the image holds every core's code in one region; the plain texts cost about 35 KiB of it).\n"
         "struct PortdiagTest { const char *name; uint32_t size, zsize; const uint8_t *z; };\n")
    for i, n in enumerate(names):
        data = open(os.path.join(SRC, n), "rb").read()
        s += "static const uint8_t portdiag_z%d[] = {\n        %s };\n" % (i, c_bytes(raw_deflate(data)))
    s += "static const PortdiagTest portdiag_tests[] = {\n"
    for i, n in enumerate(names):
        data = open(os.path.join(SRC, n), "rb").read()
        z = raw_deflate(data)
        s += '    { "%s", %d, %d, portdiag_z%d },\n' % (n, len(data), len(z), i)
    s += "};\n#define PORTDIAG_NTESTS %d\n" % len(names)
    old = sorted(f for f in os.listdir(OLD) if f.endswith(".toml")) if os.path.isdir(OLD) else []
    # the earlier texts are kept as size + FNV-1a 64 only: the image holds every core's code in one region and the full texts cost about 35 KiB of it
    s += "struct PortdiagOld { const char *name; uint32_t size; uint32_t hash_hi, hash_lo; };\n"
    s += "static const PortdiagOld portdiag_superseded[] = {\n"
    for n in old:
        base = n.split(".")[0] + ".toml"           # cd32.v1.toml -> cd32.toml
        data = open(os.path.join(OLD, n), "rb").read()
        h = fnv64(data)
        s += '    { "%s", %d, 0x%08xu, 0x%08xu },\n' % (base, len(data), h >> 32, h & 0xFFFFFFFF)
    s += "    { 0, 0, 0, 0 }\n};\n"
    return s


def main(argv):
    text = render()
    if "--check" in argv:
        have = open(INC).read() if os.path.exists(INC) else ""
        # the deflate bytes depend on the zlib build: the check compares the hash of the sources, not the stream
        if have.split("\n", 1)[0] != text.split("\n", 1)[0]:
            sys.exit("gen_diag_tests: %s is not what cores/diag/sd/tests gives; run tools/gen_diag_tests.py" % os.path.relpath(INC, ROOT))
        print("portdiag_tests.inc is current")
        return
    open(INC, "w").write(text)
    print("wrote %s" % os.path.relpath(INC, ROOT))


if __name__ == "__main__":
    main(sys.argv[1:])
